    staff_code varchar(20) NOT NULL,
    full_name varchar(255),
    email varchar(100),
    org_id bigint,
    target_user_id varchar(20),
    password_hash varchar(255),
    resolved_by varchar(20),
    resolved_time timestamptz,
    resolution_note varchar(500),
    row_version bigint NOT NULL DEFAULT 0,
    create_time timestamptz NOT NULL DEFAULT now(),
    update_time timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_access_requests_kind CHECK (kind IN ('REGISTER', 'PASSWORD_RESET')),
    CONSTRAINT ck_access_requests_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    CONSTRAINT ck_access_requests_resolved CHECK (
        (status = 'PENDING' AND resolved_by IS NULL AND resolved_time IS NULL)
        OR (status <> 'PENDING' AND resolved_by IS NOT NULL AND resolved_time IS NOT NULL))
);
