-- CORE ACADEMY - IDENTITY / ORGANIZATION / RBAC TINH GON (8 BANG)
-- PostgreSQL 14+. FRESH INSTALL ONLY. KHONG CHAY DE LEN SCHEMA 75 BANG DA TON TAI.
-- Phan quyen FE theo MA MAN HINH; backend kiem tra role + scope + hanh dong API.
-- Khong khai bao FOREIGN KEY vat ly; Service phai kiem tra moi quan he logic.
BEGIN;
CREATE SCHEMA IF NOT EXISTS learning_hub;

-- 1. Cay don vi/phong ban. Khong suy dien BRN/BRCD/CRA la cap cha-con.
CREATE TABLE learning_hub.orgs (
        org_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        parent_id bigint,
        org_type varchar(20) NOT NULL,
        code varchar(50) NOT NULL,
        name varchar(255) NOT NULL,
        status varchar(20) NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive')),
        sort_no integer NOT NULL DEFAULT 0,
        create_time timestamptz NOT NULL DEFAULT now(),
        update_time timestamptz NOT NULL DEFAULT now()
             );
COMMENT ON TABLE learning_hub.orgs IS 'Cây đơn vị, phòng ban; parent_id là quan hệ logic tự tham chiếu.';
CREATE INDEX idx_compact_orgs_parent ON learning_hub.orgs(parent_id);
CREATE INDEX idx_compact_orgs_code ON learning_hub.orgs(org_type,code);

-- 2. Nhom chuyen mon trong don vi. KHONG phai lop hoc.
CREATE TABLE learning_hub.teams (
        team_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        org_id bigint NOT NULL,
        code varchar(50),
        name varchar(255) NOT NULL,
        description text,
        status varchar(20) NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive')),
        create_time timestamptz NOT NULL DEFAULT now()
             );
COMMENT ON TABLE learning_hub.teams IS 'Nhóm chuyên môn thuộc một đơn vị; teams.org_id tham chiếu logic orgs.';
CREATE INDEX idx_compact_teams_org ON learning_hub.teams(org_id);

-- 3. Ho so, mot don vi va mot nhom chinh; vi tri la text de bot bang.
-- password_hash CHI phuc vu tai khoan LOCAL; voi SSO de NULL va khong luu mat khau SSO.
CREATE TABLE learning_hub.users (
        user_id varchar(20) PRIMARY KEY,
        user_name varchar(100) NOT NULL UNIQUE,
        email varchar(100),
        full_name varchar(255) NOT NULL,
        org_id bigint,
        team_id bigint,
        position_name varchar(255),
        brn varchar(20),
        brcd varchar(20),
        cra varchar(20),
        brn_name varchar(255),
        brcd_name varchar(255),
        cra_name varchar(255),
        dept_code varchar(50),
        dept_name varchar(255),
        bds_code varchar(20),
        bds_name varchar(255),
        qlns_brn_code varchar(20),
        auth_provider varchar(20) NOT NULL DEFAULT 'LOCAL' CHECK (auth_provider IN ('LOCAL','SSO')),
        password_hash varchar(255),
        password_changed_time timestamptz,
        status varchar(20) NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive','locked')),
        auth_ver bigint NOT NULL DEFAULT 0,
        last_sync_time timestamptz,
        create_time timestamptz NOT NULL DEFAULT now(),
        update_time timestamptz NOT NULL DEFAULT now(),
        CONSTRAINT ck_compact_local_password CHECK (auth_provider <> 'LOCAL' OR password_hash IS NOT NULL)
             );
COMMENT ON TABLE learning_hub.users IS 'Hồ sơ cán bộ, trạng thái tài khoản, đơn vị/nhóm/chức danh chính; giữ BRN, BRCD, CRA nguồn.';
COMMENT ON COLUMN learning_hub.users.org_id IS 'Đơn vị chính; chỉ hỗ trợ một đơn vị chính trên hồ sơ.';
COMMENT ON COLUMN learning_hub.users.team_id IS 'Nhóm chuyên môn chính; nhóm phải thuộc org_id tương ứng.';
COMMENT ON COLUMN learning_hub.users.password_hash IS 'Chỉ lưu password hash mạnh cho tài khoản LOCAL, tuyệt đối không lưu plaintext hoặc mật khẩu SSO.';
COMMENT ON COLUMN learning_hub.users.auth_ver IS 'Tăng khi thay đổi trạng thái/role/phạm vi để làm mất hiệu lực cache/token cũ.';
CREATE INDEX idx_compact_users_org ON learning_hub.users(org_id);
CREATE INDEX idx_compact_users_team ON learning_hub.users(team_id);
CREATE INDEX idx_compact_users_source ON learning_hub.users(brn,brcd,cra);

-- 4. Danh muc vai tro. ADMIN + ORG la admin don vi, ADMIN + GLOBAL la admin he thong.
CREATE TABLE learning_hub.roles (
        role_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        code varchar(50) NOT NULL UNIQUE,
        name varchar(255) NOT NULL,
        description text,
        active boolean NOT NULL DEFAULT true
             );
COMMENT ON TABLE learning_hub.roles IS 'Vai trò cấp quyền theo màn hình; quyền thực tế còn phụ thuộc scope gắn trên user_roles.';

-- 5. Danh muc man hinh cho Angular. route chi de dieu huong, KHONG phai co che bao mat API.
CREATE TABLE learning_hub.functions (
        function_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        code varchar(80) NOT NULL UNIQUE,
        name varchar(255) NOT NULL,
        route_pattern varchar(255),
        parent_function_id bigint,
        sort_no integer NOT NULL DEFAULT 0,
        active boolean NOT NULL DEFAULT true
             );
COMMENT ON TABLE learning_hub.functions IS 'Danh mục chức năng/màn hình FE, không chia quyền đến mức button.';

-- 6. Role duoc vao nhung man hinh nao. API KHONG chi dua bang nay de chap nhan CREATE/UPDATE/DELETE.
CREATE TABLE learning_hub.role_functions (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        role_id bigint NOT NULL,
        function_id bigint NOT NULL,
        created_at timestamptz NOT NULL DEFAULT now()
             );
COMMENT ON TABLE learning_hub.role_functions IS 'Quan hệ logic nhiều-nhiều vai trò và màn hình FE.';
CREATE INDEX idx_compact_role_functions_role ON learning_hub.role_functions(role_id);
CREATE INDEX idx_compact_role_functions_function ON learning_hub.role_functions(function_id);

-- 7. Moi user duoc gan nhieu role, moi role CO SCOPE RIENG.
-- OWN chi dung cho du lieu cua chinh user; khong mac dinh cho sua khoa do nguoi khac tao.
CREATE TABLE learning_hub.user_roles (
        ur_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id varchar(20) NOT NULL,
        role_id bigint NOT NULL,
        scope varchar(15) NOT NULL CHECK (scope IN ('GLOBAL','ORG','TEAM','OWN')),
        org_id bigint,
        team_id bigint,
        active boolean NOT NULL DEFAULT true,
        granted_by varchar(20),
        create_time timestamptz NOT NULL DEFAULT now(),
        update_time timestamptz NOT NULL DEFAULT now(),
        CONSTRAINT ck_compact_scope_target CHECK (
    (scope IN ('GLOBAL','OWN') AND org_id IS NULL AND team_id IS NULL)
    OR (scope = 'ORG' AND org_id IS NOT NULL AND team_id IS NULL)
    OR (scope = 'TEAM' AND team_id IS NOT NULL)
  )
             );
COMMENT ON TABLE learning_hub.user_roles IS 'Role gán cho từng người trong phạm vi GLOBAL/ORG/TEAM/OWN; không ghép scope từ grant khác.';
CREATE INDEX idx_compact_user_roles_user ON learning_hub.user_roles(user_id,active);
CREATE INDEX idx_compact_user_roles_scope ON learning_hub.user_roles(scope,org_id,team_id);

-- 8. Nhat ky cho thay doi tai khoan, role, scope va noi dung quan trong.
CREATE TABLE learning_hub.audit_log (
        audit_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        actor_id varchar(20),
        action varchar(100) NOT NULL,
        entity_type varchar(50),
        entity_id varchar(100),
        details jsonb NOT NULL DEFAULT '{}'::jsonb,
        create_time timestamptz NOT NULL DEFAULT now()
             );
COMMENT ON TABLE learning_hub.audit_log IS 'Nhật ký các thay đổi quan trọng, nhất là gán quyền và thay đổi trạng thái user.';
CREATE INDEX idx_compact_audit_entity ON learning_hub.audit_log(entity_type,entity_id,create_time DESC);

