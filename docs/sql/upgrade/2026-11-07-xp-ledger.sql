-- XP ledger (gamification group A): append-only xp_ledger and immutable gamification_config_versions.
-- Run once on a DB that already has the Learning baseline (a new DB gets the tables from learning_hub_learning.sql).
-- Single transaction: running it twice fails at CREATE TABLE and changes nothing. No data is changed.
-- The backend refuses to start without these tables (ddl-auto=validate): run it BEFORE deploying the backend.
--   psql -h <host> -U <user> -d <database> -v ON_ERROR_STOP=1 -f docs/sql/upgrade/2026-11-07-xp-ledger.sql
-- Config version 1 is created by the backend on first use from app.learning.points.*.
-- Rollback: docs/sql/upgrade/2026-11-07-xp-ledger.rollback.sql
BEGIN;
SET LOCAL lock_timeout = '5s';

CREATE TABLE learning_hub.gamification_config_versions (
    version_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_no integer NOT NULL,
    lesson_xp integer NOT NULL,
    quiz_pass_xp integer NOT NULL,
    first_try_bonus_xp integer NOT NULL,
    first_try_threshold_percent integer NOT NULL,
    community_xp integer NOT NULL,
    community_daily_cap integer NOT NULL,
    created_by varchar(20),
    create_time timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_gamification_config_versions_no UNIQUE (version_no),
    CONSTRAINT ck_gamification_config_versions_xp CHECK (lesson_xp >= 0 AND quiz_pass_xp >= 0
        AND first_try_bonus_xp >= 0 AND community_xp >= 0 AND community_daily_cap >= 0),
    CONSTRAINT ck_gamification_config_versions_threshold CHECK (first_try_threshold_percent BETWEEN 0 AND 100)
);
COMMENT ON TABLE learning_hub.gamification_config_versions IS 'Phiên bản cấu hình XP; bất biến, mỗi lần lưu thêm một dòng mới và áp dụng từ lúc lưu. Phiên bản 1 do backend tạo từ app.learning.points.* khi chưa có dòng nào.';
COMMENT ON COLUMN learning_hub.gamification_config_versions.version_id IS 'ID tự tăng của phiên bản.';
COMMENT ON COLUMN learning_hub.gamification_config_versions.version_no IS 'Số thứ tự phiên bản, tăng dần từ 1; phiên bản lớn nhất đang áp dụng.';
COMMENT ON COLUMN learning_hub.gamification_config_versions.lesson_xp IS 'XP cho mỗi bài học hoàn thành lần đầu.';
COMMENT ON COLUMN learning_hub.gamification_config_versions.quiz_pass_xp IS 'XP cho mỗi bài kiểm tra đạt lần đầu.';
COMMENT ON COLUMN learning_hub.gamification_config_versions.first_try_bonus_xp IS 'XP thưởng thêm khi đạt ngay lượt đầu với điểm từ ngưỡng trở lên.';
COMMENT ON COLUMN learning_hub.gamification_config_versions.first_try_threshold_percent IS 'Ngưỡng điểm % của thưởng đạt ngay lần đầu.';
COMMENT ON COLUMN learning_hub.gamification_config_versions.community_xp IS 'XP cho mỗi đóng góp hữu ích trong cộng đồng.';
COMMENT ON COLUMN learning_hub.gamification_config_versions.community_daily_cap IS 'XP cộng đồng tối đa mỗi người mỗi ngày (Asia/Ho_Chi_Minh).';
COMMENT ON COLUMN learning_hub.gamification_config_versions.created_by IS 'Mã cán bộ lưu phiên bản; null với phiên bản gieo từ cấu hình ứng dụng.';
COMMENT ON COLUMN learning_hub.gamification_config_versions.create_time IS 'DB sinh thời điểm lưu phiên bản.';

CREATE TABLE learning_hub.xp_ledger (
    entry_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id varchar(20) NOT NULL,
    amount integer NOT NULL,
    occurred_at timestamptz NOT NULL,
    source_kind varchar(30) NOT NULL,
    source_ref varchar(100) NOT NULL,
    config_version_id bigint NOT NULL,
    reason varchar(500),
    create_time timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_xp_ledger_source UNIQUE (user_id, source_kind, source_ref),
    CONSTRAINT ck_xp_ledger_kind CHECK (source_kind IN ('LESSON', 'QUIZ_PASS', 'QUIZ_FIRST_TRY_BONUS', 'COURSE',
        'COMMUNITY', 'ADJUSTMENT')),
    CONSTRAINT ck_xp_ledger_amount CHECK (amount >= 0 OR source_kind = 'ADJUSTMENT')
);
COMMENT ON TABLE learning_hub.xp_ledger IS 'Sổ ghi XP chỉ cộng thêm: mỗi dòng một lần nhận XP. Trigger chặn UPDATE và DELETE; sửa sai bằng dòng ADJUSTMENT. Khóa duy nhất (user, loại nguồn, mã nguồn) làm việc ghi idempotent.';
COMMENT ON COLUMN learning_hub.xp_ledger.entry_id IS 'ID tự tăng của dòng.';
COMMENT ON COLUMN learning_hub.xp_ledger.user_id IS 'Mã cán bộ người học (users.user_id, ID logic không FK).';
COMMENT ON COLUMN learning_hub.xp_ledger.amount IS 'Số XP; chỉ ADJUSTMENT được âm.';
COMMENT ON COLUMN learning_hub.xp_ledger.occurred_at IS 'Thời điểm sự kiện sinh XP; bảng xếp hạng theo kỳ tính theo cột này (Asia/Ho_Chi_Minh).';
COMMENT ON COLUMN learning_hub.xp_ledger.source_kind IS 'LESSON | QUIZ_PASS | QUIZ_FIRST_TRY_BONUS | COURSE | COMMUNITY | ADJUSTMENT.';
COMMENT ON COLUMN learning_hub.xp_ledger.source_ref IS 'Mã thực thể nguồn: bài học gốc, đề, khóa, đóng góp hoặc mã điều chỉnh.';
COMMENT ON COLUMN learning_hub.xp_ledger.config_version_id IS 'Phiên bản cấu hình dùng lúc ghi (ID logic không FK).';
COMMENT ON COLUMN learning_hub.xp_ledger.reason IS 'Lý do, bắt buộc với ADJUSTMENT.';
COMMENT ON COLUMN learning_hub.xp_ledger.create_time IS 'DB sinh thời điểm ghi dòng.';

CREATE FUNCTION learning_hub.xp_ledger_append_only() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'xp_ledger is append-only';
END;
$$;
CREATE TRIGGER trg_xp_ledger_append_only BEFORE UPDATE OR DELETE ON learning_hub.xp_ledger
    FOR EACH ROW EXECUTE FUNCTION learning_hub.xp_ledger_append_only();

CREATE INDEX idx_xp_ledger_user_time ON learning_hub.xp_ledger (user_id, occurred_at);
CREATE INDEX idx_xp_ledger_source ON learning_hub.xp_ledger (source_kind, source_ref);

COMMIT;
