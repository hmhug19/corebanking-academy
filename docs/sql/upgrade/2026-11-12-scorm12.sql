-- Independent SCORM 1.2 lecture library. Review and run once before deploying SCORM support.
BEGIN;
CREATE TABLE IF NOT EXISTS learning_hub.scorm_packages (
    package_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_org_id bigint NOT NULL,
    uploaded_by varchar(20) NOT NULL,
    title varchar(255) NOT NULL,
    original_name varchar(255) NOT NULL,
    launch_path varchar(1000) NOT NULL,
    files jsonb NOT NULL,
    warnings jsonb NOT NULL DEFAULT '[]',
    size_bytes bigint NOT NULL,
    file_count integer NOT NULL,
    mastery_score numeric(5,2),
    published boolean NOT NULL DEFAULT false,
    row_version bigint NOT NULL DEFAULT 0,
    create_time timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_scorm_packages_org ON learning_hub.scorm_packages(owner_org_id, package_id DESC);
CREATE TABLE IF NOT EXISTS learning_hub.scorm_registrations (
    registration_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    package_id bigint NOT NULL,
    user_id varchar(20) NOT NULL,
    preview boolean NOT NULL DEFAULT false,
    cmi jsonb NOT NULL DEFAULT '{}',
    total_seconds numeric(12,2) NOT NULL DEFAULT 0,
    session_seconds numeric(12,2) NOT NULL DEFAULT 0,
    launch_token_hash varchar(64),
    launch_expires_at timestamptz,
    authorization_version bigint NOT NULL DEFAULT 0,
    last_sequence bigint NOT NULL DEFAULT 0,
    last_payload_hash varchar(64),
    update_time timestamptz NOT NULL DEFAULT now(),
    UNIQUE(package_id, user_id, preview)
);
CREATE UNIQUE INDEX IF NOT EXISTS ix_scorm_launch_token ON learning_hub.scorm_registrations(launch_token_hash)
    WHERE launch_token_hash IS NOT NULL;
COMMENT ON TABLE learning_hub.scorm_registrations IS 'SCORM runtime state per learner and package; preview is isolated';
COMMENT ON COLUMN learning_hub.scorm_registrations.launch_token_hash IS 'SHA-256 of limited player capability; never stores LMS bearer tokens';
COMMIT;
