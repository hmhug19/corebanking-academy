-- Kết nối trợ lý ngoài (ADR 0004): the permission a user grants so that a Trợ lý ngoài (for example Claude Code on
-- their machine) can act for them on /api/v1/mcp only. The token is shown to the user once; only its SHA-256 hash and
-- a short prefix for display are stored, never the token itself. A connection works until it expires (30 or 90 days),
-- is revoked, or its user loses the role it needs (checked at every call, not stored here).
-- Relations are plain id columns, no physical foreign keys (guideline §13.2).
-- Run as dev_user (the backend's role). Safe to run again.
-- The backend uses this table through JDBC: run it BEFORE deploying the backend.
--   psql -h <host> -U dev_user -d <database> -v ON_ERROR_STOP=1 -f docs/sql/upgrade/2026-11-27-external-assistant-connections.sql
-- Rollback: docs/sql/upgrade/2026-11-27-external-assistant-connections.rollback.sql
BEGIN;
SET LOCAL lock_timeout = '5s';

CREATE TABLE IF NOT EXISTS learning_hub.external_assistant_connection (
    connection_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id varchar(20) NOT NULL,
    name varchar(100) NOT NULL,
    token_hash char(64) NOT NULL,
    token_prefix varchar(20) NOT NULL,
    create_time timestamptz NOT NULL DEFAULT now(),
    expires_at timestamptz NOT NULL,
    last_used_at timestamptz,
    revoked_at timestamptz,
    CONSTRAINT uq_external_assistant_connection_token UNIQUE (token_hash)
);
COMMENT ON TABLE learning_hub.external_assistant_connection IS
    'Kết nối trợ lý ngoài: quyền một người dùng cấp cho trợ lý bên ngoài gọi /api/v1/mcp thay mình.';
COMMENT ON COLUMN learning_hub.external_assistant_connection.user_id IS 'Người tạo kết nối (users.user_id); trợ lý ngoài hành động với đúng quyền hiện tại của người này.';
COMMENT ON COLUMN learning_hub.external_assistant_connection.name IS 'Tên người dùng đặt để nhận ra kết nối.';
COMMENT ON COLUMN learning_hub.external_assistant_connection.token_hash IS 'SHA-256 (hex) của token; token chỉ hiện một lần lúc tạo và không bao giờ được lưu hay ghi log.';
COMMENT ON COLUMN learning_hub.external_assistant_connection.token_prefix IS 'Vài ký tự đầu của token để người dùng nhận ra kết nối.';
COMMENT ON COLUMN learning_hub.external_assistant_connection.expires_at IS 'Hết hạn sau 30 hoặc 90 ngày kể từ lúc tạo.';
COMMENT ON COLUMN learning_hub.external_assistant_connection.last_used_at IS 'Lần trợ lý ngoài dùng kết nối gần nhất, cập nhật tối đa mỗi phút một lần.';
COMMENT ON COLUMN learning_hub.external_assistant_connection.revoked_at IS 'Lúc người dùng thu hồi; NULL khi còn hiệu lực.';

CREATE INDEX IF NOT EXISTS idx_external_assistant_connection_user
    ON learning_hub.external_assistant_connection (user_id, create_time DESC);

COMMIT;
