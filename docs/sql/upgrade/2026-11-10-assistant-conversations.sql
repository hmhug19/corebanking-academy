-- Assistant conversations: what a user asked the AI assistants (quick chat and /assistant) and what it answered,
-- kept on the server so a conversation can be reopened on any device and the next question has its earlier turns.
-- Run once on a DB that already has the Identity baseline. Safe to run again: it only adds what is missing.
-- The backend refuses to start without these tables (ddl-auto=validate): run it BEFORE deploying the backend.
--   psql -h <host> -U <user> -d <database> -v ON_ERROR_STOP=1 -f docs/sql/upgrade/2026-11-10-assistant-conversations.sql
-- Rollback: docs/sql/upgrade/2026-11-10-assistant-conversations.rollback.sql
BEGIN;
SET LOCAL lock_timeout = '5s';

CREATE TABLE IF NOT EXISTS learning_hub.assistant_conversations (
    conversation_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id varchar(20) NOT NULL,
    title varchar(80) NOT NULL,
    last_activity_time timestamptz NOT NULL DEFAULT now(),
    create_time timestamptz NOT NULL DEFAULT now(),
    update_time timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE learning_hub.assistant_conversations IS
    'Hội thoại của một người dùng với trợ lý AI (trợ lý nhanh và /assistant dùng chung). Chỉ chủ sở hữu đọc được; xoá là xoá hẳn. Quan hệ bằng cột ID thông thường, không FK.';
COMMENT ON COLUMN learning_hub.assistant_conversations.conversation_id IS 'ID tự tăng của hội thoại.';
COMMENT ON COLUMN learning_hub.assistant_conversations.owner_id IS 'Chủ hội thoại (users.user_id, ID logic không FK).';
COMMENT ON COLUMN learning_hub.assistant_conversations.title IS 'Câu hỏi đầu tiên cắt còn 80 ký tự, hoặc tên do người dùng đặt.';
COMMENT ON COLUMN learning_hub.assistant_conversations.last_activity_time IS 'Lần hỏi gần nhất; công việc dọn nền xoá hội thoại không hoạt động quá app.assistant.history.retention.';
COMMENT ON COLUMN learning_hub.assistant_conversations.create_time IS 'DB sinh thời điểm tạo.';
COMMENT ON COLUMN learning_hub.assistant_conversations.update_time IS 'JPA cập nhật thời điểm thay đổi.';

CREATE INDEX IF NOT EXISTS idx_assistant_conversations_owner
    ON learning_hub.assistant_conversations(owner_id, last_activity_time DESC);
CREATE INDEX IF NOT EXISTS idx_assistant_conversations_activity
    ON learning_hub.assistant_conversations(last_activity_time);

CREATE TABLE IF NOT EXISTS learning_hub.assistant_turns (
    turn_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id bigint NOT NULL,
    surface varchar(20) NOT NULL,
    question text NOT NULL,
    answer text,
    citations jsonb NOT NULL DEFAULT '[]'::jsonb,
    tool_names jsonb NOT NULL DEFAULT '[]'::jsonb,
    navigation jsonb,
    action_id varchar(40),
    skill varchar(40),
    prompt_version varchar(40),
    status varchar(20) NOT NULL,
    first_token_ms integer,
    duration_ms integer,
    create_time timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_assistant_turns_surface CHECK (surface IN ('AGENT', 'KNOWLEDGE')),
    CONSTRAINT ck_assistant_turns_status CHECK (status IN ('DONE', 'ERROR', 'STOPPED'))
);
COMMENT ON TABLE learning_hub.assistant_turns IS
    'Một lượt hỏi-đáp trong hội thoại, lưu đủ văn bản câu hỏi và câu trả lời. Log không bao giờ chứa văn bản này.';
COMMENT ON COLUMN learning_hub.assistant_turns.turn_id IS 'ID tự tăng của lượt.';
COMMENT ON COLUMN learning_hub.assistant_turns.conversation_id IS 'Hội thoại chứa lượt (assistant_conversations.conversation_id, ID logic không FK); xoá hội thoại thì service xoá các lượt.';
COMMENT ON COLUMN learning_hub.assistant_turns.surface IS 'Nơi hỏi: AGENT (trợ lý nhanh) | KNOWLEDGE (hỏi đáp tài liệu ở /assistant).';
COMMENT ON COLUMN learning_hub.assistant_turns.question IS 'Câu hỏi của người dùng, đã bỏ khoảng trắng hai đầu.';
COMMENT ON COLUMN learning_hub.assistant_turns.answer IS 'Câu trả lời cuối cùng; NULL khi lượt lỗi hoặc bị dừng trước khi có câu trả lời.';
COMMENT ON COLUMN learning_hub.assistant_turns.citations IS 'Trích dẫn của câu trả lời (mảng JSON; mỗi phần tử gồm n, fileName, page, lineStart, lineEnd, snippet).';
COMMENT ON COLUMN learning_hub.assistant_turns.tool_names IS 'Tên các công cụ đã chạy trong lượt (mảng JSON).';
COMMENT ON COLUMN learning_hub.assistant_turns.navigation IS 'Màn hình trợ lý đã mở trong lượt ({path, title}); NULL nếu không có.';
COMMENT ON COLUMN learning_hub.assistant_turns.action_id IS 'Mã yêu cầu thay đổi dữ liệu chờ xác nhận do lượt này đề xuất; NULL nếu không có.';
COMMENT ON COLUMN learning_hub.assistant_turns.skill IS 'Kỹ năng đã trả lời lượt này; NULL cho đến khi có kỹ năng.';
COMMENT ON COLUMN learning_hub.assistant_turns.prompt_version IS 'Phiên bản prompt đã dùng, để truy vết đánh giá về prompt; NULL cho đến khi có kỹ năng.';
COMMENT ON COLUMN learning_hub.assistant_turns.status IS 'DONE (xong) | ERROR (lỗi giữa chừng) | STOPPED (người dùng dừng hoặc ngắt kết nối).';
COMMENT ON COLUMN learning_hub.assistant_turns.first_token_ms IS 'Thời gian tới ký tự đầu tiên của câu trả lời, mili giây; NULL nếu chưa có.';
COMMENT ON COLUMN learning_hub.assistant_turns.duration_ms IS 'Tổng thời gian của lượt, mili giây.';
COMMENT ON COLUMN learning_hub.assistant_turns.create_time IS 'DB sinh thời điểm tạo.';

CREATE INDEX IF NOT EXISTS idx_assistant_turns_conversation
    ON learning_hub.assistant_turns(conversation_id, turn_id);

COMMIT;
