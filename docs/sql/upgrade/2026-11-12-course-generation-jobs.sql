-- Course generation by AI: one job per generated course draft and the steps it is made of. A job keeps the inputs of the
-- start form and the uploaded source document; a step is one unit of model work (summarise, outline, one lesson, ...)
-- whose output is stored, so a single lesson can be regenerated and a restart resumes from the last finished step.
-- Relations are plain id columns, no foreign keys to other modules; steps die with their job.
-- Run once on a DB that already has the Learning and Knowledge baselines. Safe to run again.
-- The backend uses these tables through JDBC at the first request: run it BEFORE deploying the backend.
--   psql -h <host> -U <user> -d <database> -v ON_ERROR_STOP=1 -f docs/sql/upgrade/2026-11-12-course-generation-jobs.sql
-- Rollback: docs/sql/upgrade/2026-11-12-course-generation-jobs.rollback.sql
BEGIN;
SET LOCAL lock_timeout = '5s';

CREATE TABLE IF NOT EXISTS learning_hub.course_generation_jobs (
    job_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id varchar(20) NOT NULL,
    owner_org_id bigint NOT NULL,
    source_document_id bigint,
    inputs jsonb NOT NULL,
    status varchar(20) NOT NULL CHECK (status IN ('queued', 'running', 'waiting_approval', 'completed', 'failed', 'cancelled')),
    step varchar(40),
    progress integer NOT NULL DEFAULT 0 CHECK (progress BETWEEN 0 AND 100),
    error_message varchar(500),
    created_draft_id bigint,
    create_time timestamptz NOT NULL DEFAULT now(),
    update_time timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE learning_hub.course_generation_jobs IS
    'Công việc tạo khóa học bằng AI: tài liệu nguồn, thông tin form khởi tạo, trạng thái và bản nháp đã tạo.';
COMMENT ON COLUMN learning_hub.course_generation_jobs.owner_user_id IS 'Người tạo job; chỉ người này xem và hủy.';
COMMENT ON COLUMN learning_hub.course_generation_jobs.owner_org_id IS 'Đơn vị sở hữu khóa học sẽ tạo; do server quyết định, không do model.';
COMMENT ON COLUMN learning_hub.course_generation_jobs.source_document_id IS 'Tài liệu nguồn (knowledge_documents, phạm vi personal); xóa job thì xóa tài liệu.';
COMMENT ON COLUMN learning_hub.course_generation_jobs.inputs IS 'Đối tượng, trình độ, số chương/thời lượng, chương trình, năng lực.';
COMMENT ON COLUMN learning_hub.course_generation_jobs.status IS 'queued | running | waiting_approval | completed | failed | cancelled.';
COMMENT ON COLUMN learning_hub.course_generation_jobs.created_draft_id IS 'Khóa học nháp đã tạo khi job hoàn tất.';

CREATE INDEX IF NOT EXISTS idx_course_generation_jobs_owner
    ON learning_hub.course_generation_jobs (owner_user_id, create_time DESC);
CREATE INDEX IF NOT EXISTS idx_course_generation_jobs_status
    ON learning_hub.course_generation_jobs (status, create_time);

CREATE TABLE IF NOT EXISTS learning_hub.course_generation_steps (
    step_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id bigint NOT NULL REFERENCES learning_hub.course_generation_jobs (job_id) ON DELETE CASCADE,
    kind varchar(30) NOT NULL,
    item_key varchar(60) NOT NULL DEFAULT '',
    input_hash varchar(64),
    output jsonb,
    status varchar(20) NOT NULL CHECK (status IN ('pending', 'running', 'done', 'failed')),
    attempts integer NOT NULL DEFAULT 0,
    error_message varchar(500),
    started_at timestamptz,
    finished_at timestamptz,
    create_time timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_course_generation_steps_item UNIQUE (job_id, kind, item_key)
);
COMMENT ON TABLE learning_hub.course_generation_steps IS
    'Một bước làm việc của job tạo khóa học; output được lưu để tạo lại từng bài và để khởi động lại không mất việc.';
COMMENT ON COLUMN learning_hub.course_generation_steps.kind IS 'summarise_sections | outline | lesson | questions.';
COMMENT ON COLUMN learning_hub.course_generation_steps.item_key IS 'Khóa chương/bài của bước; rỗng với bước chung.';
COMMENT ON COLUMN learning_hub.course_generation_steps.input_hash IS 'Băm đầu vào, để biết bước nào cần chạy lại khi đầu vào đổi.';

CREATE INDEX IF NOT EXISTS idx_course_generation_steps_claim
    ON learning_hub.course_generation_steps (status, job_id, step_id);

COMMIT;
