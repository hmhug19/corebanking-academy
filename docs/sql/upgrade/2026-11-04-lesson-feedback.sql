-- Lesson feedback: a learner's rating, public comments, questions to the instructor and content reports on a lesson.
-- Run once on a DB that already has the Learning baseline (a new DB gets the table from learning_hub_learning.sql).
-- Safe to run again: it only adds what is missing. No data is changed.
-- The backend refuses to start without this table (ddl-auto=validate): run it BEFORE deploying the backend.
--   psql -h <host> -U <user> -d <database> -v ON_ERROR_STOP=1 -f docs/sql/upgrade/2026-11-04-lesson-feedback.sql
-- Rollback: docs/sql/upgrade/2026-11-04-lesson-feedback.rollback.sql
BEGIN;
SET LOCAL lock_timeout = '5s';

CREATE TABLE IF NOT EXISTS learning_hub.lesson_feedback (
    feedback_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id varchar(20) NOT NULL,
    lesson_id bigint NOT NULL,
    course_id bigint NOT NULL,
    kind varchar(10) NOT NULL,
    stars smallint,
    body text,
    block_id bigint,
    anchor_type varchar(10),
    pdf_page integer,
    video_second integer,
    status varchar(10),
    reply text,
    replied_by varchar(20),
    reply_time timestamptz,
    is_deleted boolean NOT NULL DEFAULT false,
    created_by varchar(20) NOT NULL,
    updated_by varchar(20) NOT NULL,
    row_version bigint NOT NULL DEFAULT 0,
    create_time timestamptz NOT NULL DEFAULT now(),
    update_time timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_lesson_feedback_kind CHECK (kind IN ('rating', 'comment', 'question', 'report')),
    CONSTRAINT ck_lesson_feedback_content CHECK (
        (kind = 'rating' AND stars IS NOT NULL AND stars BETWEEN 1 AND 5 AND body IS NULL)
        OR (kind <> 'rating' AND stars IS NULL AND body IS NOT NULL)),
    CONSTRAINT ck_lesson_feedback_status CHECK (
        (kind IN ('rating', 'comment') AND status IS NULL AND reply IS NULL AND replied_by IS NULL
            AND reply_time IS NULL)
        OR (kind IN ('question', 'report') AND status IS NOT NULL AND status IN ('new', 'answered', 'resolved'))),
    CONSTRAINT ck_lesson_feedback_anchor CHECK (
        (kind = 'rating' AND anchor_type IS NULL AND block_id IS NULL AND pdf_page IS NULL AND video_second IS NULL)
        OR (kind <> 'rating' AND anchor_type IS NOT NULL AND (
            (anchor_type = 'none' AND block_id IS NULL AND pdf_page IS NULL AND video_second IS NULL)
            OR (anchor_type = 'pdf' AND block_id IS NOT NULL AND pdf_page IS NOT NULL AND video_second IS NULL)
            OR (anchor_type = 'video' AND block_id IS NOT NULL AND video_second IS NOT NULL AND pdf_page IS NULL))))
);
COMMENT ON TABLE learning_hub.lesson_feedback IS
    'Phản hồi của học viên trên một bài học: đánh giá sao (rating), nhận xét công khai (comment), câu hỏi giảng viên (question) và báo nội dung (report). Xóa mềm bằng is_deleted. Một đánh giá sống mỗi người và bài do service bảo đảm dưới khóa advisory, không UNIQUE; quan hệ bằng cột ID thông thường, không FK.';
COMMENT ON COLUMN learning_hub.lesson_feedback.feedback_id IS 'ID tự tăng của bản ghi.';
COMMENT ON COLUMN learning_hub.lesson_feedback.user_id IS 'Mã cán bộ gửi phản hồi (users.user_id, ID logic không FK).';
COMMENT ON COLUMN learning_hub.lesson_feedback.lesson_id IS 'Bài học của phiên bản khóa học mà học viên đã nhận (course_lessons.lesson_id, ID logic không FK). Phản hồi ở lại bài nơi nó được gửi, không chuyển sang phiên bản mới.';
COMMENT ON COLUMN learning_hub.lesson_feedback.course_id IS 'Khóa học chứa bài (courses.course_id, ID logic không FK), lấy từ bài học lúc gửi để điểm đánh giá của khóa gom được qua mọi phiên bản mà không phải nối qua chương.';
COMMENT ON COLUMN learning_hub.lesson_feedback.kind IS 'Loại phản hồi: rating (đánh giá sao) | comment (nhận xét công khai) | question (hỏi giảng viên, riêng tư) | report (báo nội dung, riêng tư).';
COMMENT ON COLUMN learning_hub.lesson_feedback.stars IS 'Số sao nguyên từ 1 đến 5; chỉ có khi kind = rating.';
COMMENT ON COLUMN learning_hub.lesson_feedback.body IS 'Nội dung đã cắt khoảng trắng đầu cuối, 5 đến 1000 ký tự; NULL khi kind = rating.';
COMMENT ON COLUMN learning_hub.lesson_feedback.block_id IS 'Khối chứa vị trí neo (lesson_blocks.block_id, ID logic không FK); NULL khi anchor_type = none và khi kind = rating.';
COMMENT ON COLUMN learning_hub.lesson_feedback.anchor_type IS 'Loại neo: none (cả bài) | pdf (một trang) | video (một giây); NULL khi kind = rating.';
COMMENT ON COLUMN learning_hub.lesson_feedback.pdf_page IS 'Số trang PDF, từ 1 đến assets.page_count; chỉ có khi anchor_type = pdf.';
COMMENT ON COLUMN learning_hub.lesson_feedback.video_second IS 'Giây video nguyên, từ 0 đến phần nguyên của assets.duration_seconds; chỉ có khi anchor_type = video.';
COMMENT ON COLUMN learning_hub.lesson_feedback.status IS 'Trạng thái xử lý: new (mới gửi) | answered (đã trả lời) | resolved (đã xử lý); chỉ có khi kind = question hoặc report, NULL với rating và comment.';
COMMENT ON COLUMN learning_hub.lesson_feedback.reply IS 'Nội dung giảng viên trả lời; chỉ có khi kind = question hoặc report và đã được trả lời.';
COMMENT ON COLUMN learning_hub.lesson_feedback.replied_by IS 'Mã cán bộ trả lời (users.user_id, ID logic không FK).';
COMMENT ON COLUMN learning_hub.lesson_feedback.reply_time IS 'Thời điểm trả lời.';
COMMENT ON COLUMN learning_hub.lesson_feedback.is_deleted IS 'Xóa mềm: true là đã xóa, mọi truy vấn của học viên bỏ qua dòng này.';
COMMENT ON COLUMN learning_hub.lesson_feedback.created_by IS 'Mã cán bộ tạo bản ghi.';
COMMENT ON COLUMN learning_hub.lesson_feedback.updated_by IS 'Mã cán bộ cập nhật gần nhất.';
COMMENT ON COLUMN learning_hub.lesson_feedback.row_version IS 'Optimistic locking chống ghi đè thay đổi.';
COMMENT ON COLUMN learning_hub.lesson_feedback.create_time IS 'DB sinh thời điểm tạo.';
COMMENT ON COLUMN learning_hub.lesson_feedback.update_time IS 'JPA cập nhật thời điểm thay đổi.';

CREATE INDEX IF NOT EXISTS idx_lesson_feedback_lesson_kind
    ON learning_hub.lesson_feedback (lesson_id, kind, create_time DESC) WHERE NOT is_deleted;
CREATE INDEX IF NOT EXISTS idx_lesson_feedback_course_rating
    ON learning_hub.lesson_feedback (course_id) WHERE kind = 'rating' AND NOT is_deleted;

COMMIT;
