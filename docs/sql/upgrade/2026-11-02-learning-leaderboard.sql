-- Learning leaderboard: one row per user per local day (Asia/Ho_Chi_Minh) on which the user learned.
-- Run once on a DB that already has the Learning baseline (a new DB gets the table from learning_hub_learning.sql).
-- Safe to run again: it only adds what is missing. No data is changed.
-- The backend refuses to start without this table (ddl-auto=validate): run it BEFORE deploying the backend.
--   psql -h <host> -U <user> -d <database> -v ON_ERROR_STOP=1 -f docs/sql/upgrade/2026-11-02-learning-leaderboard.sql
-- Optional: give existing users a streak from their past progress and attempts:
--   docs/sql/upgrade/2026-11-02-learning-leaderboard-backfill.sql
-- Rollback: docs/sql/upgrade/2026-11-02-learning-leaderboard.rollback.sql
BEGIN;
SET LOCAL lock_timeout = '5s';

CREATE TABLE IF NOT EXISTS learning_hub.learning_activity_days (
    activity_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id varchar(20) NOT NULL,
    activity_date date NOT NULL,
    first_source varchar(20) NOT NULL,
    create_time timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE learning_hub.learning_activity_days IS
    'Ngày có hoạt động học của người dùng (theo Asia/Ho_Chi_Minh); chỉ thêm, không sửa. Một dòng mỗi người mỗi ngày do service bảo đảm dưới khóa advisory, không UNIQUE.';
COMMENT ON COLUMN learning_hub.learning_activity_days.activity_id IS 'ID tự tăng của bản ghi.';
COMMENT ON COLUMN learning_hub.learning_activity_days.user_id IS 'Mã cán bộ người học (users.user_id, ID logic không FK).';
COMMENT ON COLUMN learning_hub.learning_activity_days.activity_date IS 'Ngày học theo giờ Asia/Ho_Chi_Minh, không phải ngày UTC.';
COMMENT ON COLUMN learning_hub.learning_activity_days.first_source IS 'Hoạt động đầu tiên trong ngày: session | block_progress | quiz | backfill.';
COMMENT ON COLUMN learning_hub.learning_activity_days.create_time IS 'DB sinh thời điểm ghi dòng.';

CREATE INDEX IF NOT EXISTS idx_learning_activity_days_user_date
    ON learning_hub.learning_activity_days (user_id, activity_date DESC);

COMMIT;
