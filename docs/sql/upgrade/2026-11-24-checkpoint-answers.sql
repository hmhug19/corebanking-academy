-- PostgreSQL 14+. Chạy một lần sau baseline Identity, Learning, Assessment và flashcards, bằng role dev_user
-- để bảng mới thuộc dev_user và backend (DB_USER=dev_user) truy cập được; không cần GRANT thêm.
BEGIN;

CREATE TABLE learning_hub.checkpoint_answers (
    answer_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id varchar(20) NOT NULL,
    lesson_id bigint NOT NULL,
    question_id bigint NOT NULL,
    question_version bigint NOT NULL CHECK (question_version >= 0),
    competency_id bigint NOT NULL,
    correct boolean NOT NULL,
    answered_at timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE learning_hub.checkpoint_answers IS 'Câu trả lời của học viên cho câu hỏi nhanh cuối bài; không tính điểm, XP hay tiến độ.';
COMMENT ON COLUMN learning_hub.checkpoint_answers.lesson_id IS 'Bài học chứa câu hỏi nhanh, tham chiếu logic.';
COMMENT ON COLUMN learning_hub.checkpoint_answers.question_id IS 'Câu hỏi nguồn (flashcard đã công bố), tham chiếu logic.';
COMMENT ON COLUMN learning_hub.checkpoint_answers.question_version IS 'questions.row_version tại lúc trả lời.';
COMMENT ON COLUMN learning_hub.checkpoint_answers.competency_id IS 'Nhóm năng lực của câu hỏi tại lúc trả lời, phục vụ gợi ý ôn tập.';

CREATE INDEX ix_checkpoint_answers_user_lesson ON learning_hub.checkpoint_answers (user_id, lesson_id);
CREATE INDEX ix_checkpoint_answers_user_competency ON learning_hub.checkpoint_answers (user_id, competency_id);

COMMIT;
