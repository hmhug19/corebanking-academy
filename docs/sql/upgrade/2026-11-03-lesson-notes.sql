-- Lesson notes and bookmarks: a learner's private notes and bookmarks on a lesson, anchored to a PDF page or a video second.
-- Run once on a DB that already has the Learning baseline (a new DB gets both tables from learning_hub_learning.sql).
-- Safe to run again: it only adds what is missing. No data is changed.
-- The backend refuses to start without these tables (ddl-auto=validate): run it BEFORE deploying the backend.
--   psql -h <host> -U <user> -d <database> -v ON_ERROR_STOP=1 -f docs/sql/upgrade/2026-11-03-lesson-notes.sql
-- Rollback: docs/sql/upgrade/2026-11-03-lesson-notes.rollback.sql
BEGIN;
SET LOCAL lock_timeout = '5s';

CREATE TABLE IF NOT EXISTS learning_hub.lesson_notes (
    note_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id varchar(20) NOT NULL,
    lesson_id bigint NOT NULL,
    block_id bigint,
    anchor_type varchar(10) NOT NULL,
    pdf_page integer,
    video_second integer,
    body text NOT NULL,
    is_deleted boolean NOT NULL DEFAULT false,
    created_by varchar(20) NOT NULL,
    updated_by varchar(20) NOT NULL,
    row_version bigint NOT NULL DEFAULT 0,
    create_time timestamptz NOT NULL DEFAULT now(),
    update_time timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_lesson_notes_anchor CHECK (
        (anchor_type = 'none' AND block_id IS NULL AND pdf_page IS NULL AND video_second IS NULL)
        OR (anchor_type = 'pdf' AND block_id IS NOT NULL AND pdf_page IS NOT NULL AND video_second IS NULL)
        OR (anchor_type = 'video' AND block_id IS NOT NULL AND video_second IS NOT NULL AND pdf_page IS NULL))
);
COMMENT ON TABLE learning_hub.lesson_notes IS
    'Ghi chú riêng của học viên trên một bài học, gắn với trang PDF, giây video hoặc cả bài. Xóa mềm bằng is_deleted. Quan hệ bằng cột ID thông thường; service kiểm tra truy cập và neo, không FK.';
COMMENT ON COLUMN learning_hub.lesson_notes.note_id IS 'ID tự tăng của bản ghi.';
COMMENT ON COLUMN learning_hub.lesson_notes.user_id IS 'Mã cán bộ chủ ghi chú (users.user_id, ID logic không FK).';
COMMENT ON COLUMN learning_hub.lesson_notes.lesson_id IS 'Bài học của phiên bản khóa học mà học viên đã nhận (course_lessons.lesson_id, ID logic không FK). Ghi chú ở lại bài và khối nơi nó được viết, không chuyển sang phiên bản mới.';
COMMENT ON COLUMN learning_hub.lesson_notes.block_id IS 'Khối chứa vị trí neo (lesson_blocks.block_id, ID logic không FK); NULL khi anchor_type = none.';
COMMENT ON COLUMN learning_hub.lesson_notes.anchor_type IS 'Loại neo: none (cả bài) | pdf (một trang) | video (một giây).';
COMMENT ON COLUMN learning_hub.lesson_notes.pdf_page IS 'Số trang PDF, từ 1 đến assets.page_count; chỉ có khi anchor_type = pdf.';
COMMENT ON COLUMN learning_hub.lesson_notes.video_second IS 'Giây video nguyên, từ 0 đến phần nguyên của assets.duration_seconds; chỉ có khi anchor_type = video.';
COMMENT ON COLUMN learning_hub.lesson_notes.body IS 'Nội dung ghi chú đã cắt khoảng trắng đầu cuối, 1 đến 4000 ký tự.';
COMMENT ON COLUMN learning_hub.lesson_notes.is_deleted IS 'Xóa mềm: true là đã xóa, mọi truy vấn của học viên bỏ qua dòng này.';
COMMENT ON COLUMN learning_hub.lesson_notes.created_by IS 'Mã cán bộ tạo bản ghi.';
COMMENT ON COLUMN learning_hub.lesson_notes.updated_by IS 'Mã cán bộ cập nhật gần nhất.';
COMMENT ON COLUMN learning_hub.lesson_notes.row_version IS 'Optimistic locking chống ghi đè thay đổi.';
COMMENT ON COLUMN learning_hub.lesson_notes.create_time IS 'DB sinh thời điểm tạo.';
COMMENT ON COLUMN learning_hub.lesson_notes.update_time IS 'JPA cập nhật thời điểm thay đổi.';

CREATE TABLE IF NOT EXISTS learning_hub.lesson_bookmarks (
    bookmark_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id varchar(20) NOT NULL,
    lesson_id bigint NOT NULL,
    block_id bigint NOT NULL,
    anchor_type varchar(10) NOT NULL,
    pdf_page integer,
    video_second integer,
    label varchar(200),
    is_deleted boolean NOT NULL DEFAULT false,
    created_by varchar(20) NOT NULL,
    updated_by varchar(20) NOT NULL,
    row_version bigint NOT NULL DEFAULT 0,
    create_time timestamptz NOT NULL DEFAULT now(),
    update_time timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_lesson_bookmarks_anchor CHECK (
        (anchor_type = 'pdf' AND pdf_page IS NOT NULL AND video_second IS NULL)
        OR (anchor_type = 'video' AND video_second IS NOT NULL AND pdf_page IS NULL))
);
COMMENT ON TABLE learning_hub.lesson_bookmarks IS
    'Đánh dấu riêng của học viên trên một trang PDF hoặc một giây video. Xóa mềm bằng is_deleted. Một đánh dấu sống mỗi người, khối và vị trí do service bảo đảm dưới khóa advisory, không UNIQUE.';
COMMENT ON COLUMN learning_hub.lesson_bookmarks.bookmark_id IS 'ID tự tăng của bản ghi.';
COMMENT ON COLUMN learning_hub.lesson_bookmarks.user_id IS 'Mã cán bộ chủ đánh dấu (users.user_id, ID logic không FK).';
COMMENT ON COLUMN learning_hub.lesson_bookmarks.lesson_id IS 'Bài học của phiên bản khóa học mà học viên đã nhận (course_lessons.lesson_id, ID logic không FK).';
COMMENT ON COLUMN learning_hub.lesson_bookmarks.block_id IS 'Khối chứa vị trí đánh dấu (lesson_blocks.block_id, ID logic không FK); luôn có.';
COMMENT ON COLUMN learning_hub.lesson_bookmarks.anchor_type IS 'Loại neo: pdf (một trang) | video (một giây).';
COMMENT ON COLUMN learning_hub.lesson_bookmarks.pdf_page IS 'Số trang PDF, từ 1 đến assets.page_count; chỉ có khi anchor_type = pdf.';
COMMENT ON COLUMN learning_hub.lesson_bookmarks.video_second IS 'Giây video nguyên, từ 0 đến phần nguyên của assets.duration_seconds; chỉ có khi anchor_type = video.';
COMMENT ON COLUMN learning_hub.lesson_bookmarks.label IS 'Nhãn tùy chọn, tối đa 200 ký tự; NULL thì giao diện tự đặt nhãn từ tên khối và vị trí.';
COMMENT ON COLUMN learning_hub.lesson_bookmarks.is_deleted IS 'Xóa mềm: true là đã bỏ đánh dấu, mọi truy vấn của học viên bỏ qua dòng này.';
COMMENT ON COLUMN learning_hub.lesson_bookmarks.created_by IS 'Mã cán bộ tạo bản ghi.';
COMMENT ON COLUMN learning_hub.lesson_bookmarks.updated_by IS 'Mã cán bộ cập nhật gần nhất.';
COMMENT ON COLUMN learning_hub.lesson_bookmarks.row_version IS 'Optimistic locking chống ghi đè thay đổi.';
COMMENT ON COLUMN learning_hub.lesson_bookmarks.create_time IS 'DB sinh thời điểm tạo.';
COMMENT ON COLUMN learning_hub.lesson_bookmarks.update_time IS 'JPA cập nhật thời điểm thay đổi.';

CREATE INDEX IF NOT EXISTS idx_lesson_notes_user_lesson
    ON learning_hub.lesson_notes (user_id, lesson_id, create_time DESC) WHERE NOT is_deleted;
CREATE INDEX IF NOT EXISTS idx_lesson_bookmarks_user_lesson
    ON learning_hub.lesson_bookmarks (user_id, lesson_id, create_time DESC) WHERE NOT is_deleted;

COMMIT;
