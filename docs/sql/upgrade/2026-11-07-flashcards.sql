-- PostgreSQL 14+. Chạy sau baseline Identity, Learning và Assessment.
BEGIN;

CREATE TABLE learning_hub.flashcards (
    flashcard_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id bigint NOT NULL,
    question_id bigint NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'PUBLISHED', 'WITHDRAWN')),
    approved_question_version bigint CHECK (approved_question_version >= 0),
    first_published_at timestamptz,
    created_by varchar(20) NOT NULL,
    updated_by varchar(20) NOT NULL,
    create_time timestamptz NOT NULL DEFAULT now(),
    update_time timestamptz NOT NULL DEFAULT now(),
    row_version bigint NOT NULL DEFAULT 0 CHECK (row_version >= 0),
    UNIQUE (course_id, question_id),
    CHECK (status <> 'PUBLISHED' OR (approved_question_version IS NOT NULL AND first_published_at IS NOT NULL))
);

COMMENT ON TABLE learning_hub.flashcards IS 'Câu hỏi được quản trị viên chọn để ôn trong một khóa học.';
COMMENT ON COLUMN learning_hub.flashcards.course_id IS 'Khóa học được cấp thẻ, tham chiếu logic.';
COMMENT ON COLUMN learning_hub.flashcards.question_id IS 'Câu hỏi nguồn, tham chiếu logic.';
COMMENT ON COLUMN learning_hub.flashcards.approved_question_version IS 'questions.row_version tại thời điểm duyệt đáp án.';
COMMENT ON COLUMN learning_hub.flashcards.first_published_at IS 'Mốc công bố lần đầu, giữ lại khi thu hồi để bảo vệ đề thi.';
CREATE INDEX ix_flashcards_exposed_question ON learning_hub.flashcards (question_id)
    WHERE first_published_at IS NOT NULL;

CREATE TABLE learning_hub.flashcard_progress (
    user_id varchar(20) NOT NULL,
    flashcard_id bigint NOT NULL,
    review_status varchar(20) CHECK (review_status IN ('AGAIN', 'KNOWN')),
    is_starred boolean NOT NULL DEFAULT false,
    reviewed_question_version bigint CHECK (reviewed_question_version >= 0),
    last_reviewed_at timestamptz,
    update_time timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, flashcard_id),
    CHECK ((review_status IS NULL) = (reviewed_question_version IS NULL)),
    CHECK ((review_status IS NULL) = (last_reviewed_at IS NULL))
);

COMMENT ON TABLE learning_hub.flashcard_progress IS 'Tự đánh giá và đánh dấu thẻ theo học viên.';
COMMENT ON COLUMN learning_hub.flashcard_progress.reviewed_question_version IS 'Phiên bản câu hỏi học viên đã ôn.';
COMMENT ON COLUMN learning_hub.flashcard_progress.is_starred IS 'Đánh dấu cá nhân, độc lập với tự đánh giá.';
COMMIT;
