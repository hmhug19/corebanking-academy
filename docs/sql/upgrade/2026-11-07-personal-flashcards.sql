BEGIN;
CREATE TABLE learning_hub.personal_flashcard_decks (
    deck_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id varchar(20) NOT NULL,
    name varchar(150) NOT NULL,
    course_id bigint,
    create_time timestamptz NOT NULL DEFAULT now(),
    update_time timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_personal_flashcard_decks_user ON learning_hub.personal_flashcard_decks (user_id, deck_id);
COMMENT ON TABLE learning_hub.personal_flashcard_decks IS 'Bộ thẻ riêng do học viên tạo, khóa học gắn kèm là tùy chọn.';
CREATE TABLE learning_hub.personal_flashcards (
    card_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    deck_id bigint NOT NULL,
    prompt text NOT NULL,
    answer text NOT NULL,
    competency_id bigint,
    review_status varchar(20) CHECK (review_status IN ('AGAIN', 'KNOWN')),
    is_starred boolean NOT NULL DEFAULT false,
    create_time timestamptz NOT NULL DEFAULT now(),
    update_time timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_personal_flashcards_deck ON learning_hub.personal_flashcards (deck_id, card_id);
COMMENT ON TABLE learning_hub.personal_flashcards IS 'Nội dung và trạng thái tự đánh giá của thẻ thuộc bộ cá nhân.';
COMMIT;
