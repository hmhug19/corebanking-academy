-- Access requests: what a visitor asked for from the sign-in page (register, or reset a password), waiting for an administrator.
-- Run once on a DB that already has the Identity baseline (a new DB gets this table from learning_hub_identity.sql once it is merged there).
-- Safe to run again: it only adds what is missing. No data is changed.
-- The backend refuses to start without this table (ddl-auto=validate): run it BEFORE deploying the backend.
--   psql -h <host> -U <user> -d <database> -v ON_ERROR_STOP=1 -f docs/sql/upgrade/2026-11-05-access-requests.sql
-- Rollback: docs/sql/upgrade/2026-11-05-access-requests.rollback.sql
BEGIN;
SET LOCAL lock_timeout = '5s';

CREATE TABLE IF NOT EXISTS learning_hub.access_requests (
    request_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind varchar(20) NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'PENDING',
    staff_code varchar(20) NOT NULL,
    full_name varchar(255),
    email varchar(100),
    org_id bigint,
    target_user_id varchar(20),
    password_hash varchar(255),
    resolved_by varchar(20),
    resolved_time timestamptz,
    resolution_note varchar(500),
    row_version bigint NOT NULL DEFAULT 0,
    create_time timestamptz NOT NULL DEFAULT now(),
    update_time timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_access_requests_kind CHECK (kind IN ('REGISTER', 'PASSWORD_RESET')),
    CONSTRAINT ck_access_requests_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    CONSTRAINT ck_access_requests_resolved CHECK (
        (status = 'PENDING' AND resolved_by IS NULL AND resolved_time IS NULL)
        OR (status <> 'PENDING' AND resolved_by IS NOT NULL AND resolved_time IS NOT NULL))
);
COMMENT ON TABLE learning_hub.access_requests IS
    'Yêu cầu của khách từ màn đăng nhập: đăng ký tài khoản hoặc đặt lại mật khẩu, chờ quản trị viên xử lý. Quan hệ bằng cột ID thông thường, không FK; service kiểm tra phạm vi đơn vị.';
COMMENT ON COLUMN learning_hub.access_requests.request_id IS 'ID tự tăng của yêu cầu.';
COMMENT ON COLUMN learning_hub.access_requests.kind IS 'Loại yêu cầu: REGISTER (đăng ký) | PASSWORD_RESET (quên mật khẩu).';
COMMENT ON COLUMN learning_hub.access_requests.status IS 'Trạng thái: PENDING (chờ xử lý) | APPROVED (đã duyệt) | REJECTED (đã từ chối).';
COMMENT ON COLUMN learning_hub.access_requests.staff_code IS 'Mã cán bộ được yêu cầu (REGISTER) hoặc mã tài khoản được hỏi đến (PASSWORD_RESET); giữ nguyên số 0 đầu.';
COMMENT ON COLUMN learning_hub.access_requests.full_name IS 'Họ tên người đăng ký; chỉ có với REGISTER.';
COMMENT ON COLUMN learning_hub.access_requests.email IS 'Email người gửi nếu có.';
COMMENT ON COLUMN learning_hub.access_requests.org_id IS 'Đơn vị được chọn (REGISTER) hoặc đơn vị của tài khoản (PASSWORD_RESET) (orgs.org_id, ID logic không FK); NULL khi không có, chỉ quản trị toàn hệ thống thấy.';
COMMENT ON COLUMN learning_hub.access_requests.target_user_id IS 'PASSWORD_RESET: tài khoản khớp mã cán bộ (users.user_id, ID logic không FK); NULL khi không có tài khoản nào khớp.';
COMMENT ON COLUMN learning_hub.access_requests.password_hash IS 'Chỉ REGISTER: băm bcrypt của mật khẩu người đăng ký. Chỉ ghi, không bao giờ trả qua API hay ghi log.';
COMMENT ON COLUMN learning_hub.access_requests.resolved_by IS 'Mã cán bộ quản trị viên xử lý; NULL khi còn chờ.';
COMMENT ON COLUMN learning_hub.access_requests.resolved_time IS 'Thời điểm xử lý; NULL khi còn chờ.';
COMMENT ON COLUMN learning_hub.access_requests.resolution_note IS 'Ghi chú của quản trị viên, tối đa 500 ký tự.';
COMMENT ON COLUMN learning_hub.access_requests.row_version IS 'Optimistic locking chống ghi đè thay đổi.';
COMMENT ON COLUMN learning_hub.access_requests.create_time IS 'DB sinh thời điểm tạo.';
COMMENT ON COLUMN learning_hub.access_requests.update_time IS 'JPA cập nhật thời điểm thay đổi.';

-- One waiting request per kind and staff code: a second one is answered as sent and creates nothing.
CREATE UNIQUE INDEX IF NOT EXISTS uq_access_requests_pending
    ON learning_hub.access_requests (kind, lower(staff_code)) WHERE status = 'PENDING';
CREATE INDEX IF NOT EXISTS idx_access_requests_status_time
    ON learning_hub.access_requests (status, create_time DESC);

COMMIT;
