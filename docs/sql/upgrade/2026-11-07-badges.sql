-- Badges (gamification group A, ticket 10): badge definitions and the badges each learner earned. Run once on a DB that
-- already has 2026-11-07-levels.sql (a new DB gets the tables from learning_hub_learning.sql). Single transaction: running it
-- twice fails at CREATE TABLE and changes nothing. The starter set (first course, 10 courses, one badge per programme,
-- first-try perfect x3, before the deadline x3, streaks of 5, 20 and 60 working days) is created by the backend the first
-- time it reads badges, and everyone who already qualifies receives it silently (source BACKFILL, no notification).
--   psql -h <host> -U <user> -d <database> -v ON_ERROR_STOP=1 -f docs/sql/upgrade/2026-11-07-badges.sql
-- Rollback: docs/sql/upgrade/2026-11-07-badges.rollback.sql
BEGIN;
SET LOCAL lock_timeout = '5s';

CREATE TABLE learning_hub.badge_definitions (
    badge_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(60) NOT NULL,
    name varchar(100) NOT NULL,
    description varchar(300) NOT NULL,
    icon varchar(50) NOT NULL,
    rule_type varchar(40) NOT NULL,
    param_n integer,
    param_program_id bigint,
    status varchar(20) NOT NULL DEFAULT 'active',
    sort_no integer NOT NULL DEFAULT 0,
    created_by varchar(20),
    create_time timestamptz NOT NULL DEFAULT now(),
    update_time timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_badge_definitions_code UNIQUE (code),
    CONSTRAINT ck_badge_definitions_rule CHECK (
        (rule_type = 'PROGRAM_COMPLETED' AND param_program_id IS NOT NULL)
        OR (rule_type IN ('COURSES_COMPLETED', 'FIRST_TRY_PERFECT', 'ASSIGNED_BEFORE_DEADLINE', 'STREAK_WORKING_DAYS')
            AND param_n >= 1)),
    CONSTRAINT ck_badge_definitions_status CHECK (status IN ('active', 'retired'))
);
COMMENT ON TABLE learning_hub.badge_definitions IS 'Huy hiệu và luật đạt huy hiệu (một trong năm loại luật). Luật bị khóa khi đã có người nhận (suy ra từ user_badges); huy hiệu ngừng dùng không còn được trao nhưng người đã nhận giữ nguyên.';
COMMENT ON COLUMN learning_hub.badge_definitions.code IS 'Mã duy nhất, ổn định.';
COMMENT ON COLUMN learning_hub.badge_definitions.name IS 'Tên huy hiệu hiển thị cho học viên.';
COMMENT ON COLUMN learning_hub.badge_definitions.description IS 'Mô tả ngắn.';
COMMENT ON COLUMN learning_hub.badge_definitions.icon IS 'Tên biểu tượng Lucide.';
COMMENT ON COLUMN learning_hub.badge_definitions.rule_type IS 'COURSES_COMPLETED, PROGRAM_COMPLETED, FIRST_TRY_PERFECT, ASSIGNED_BEFORE_DEADLINE hoặc STREAK_WORKING_DAYS. HOURS_LEARNED được dành riêng, chưa xây.';
COMMENT ON COLUMN learning_hub.badge_definitions.param_n IS 'Ngưỡng N của luật (mọi loại trừ PROGRAM_COMPLETED).';
COMMENT ON COLUMN learning_hub.badge_definitions.param_program_id IS 'Chương trình (training_programs.program_id, ID logic không FK) của luật PROGRAM_COMPLETED.';
COMMENT ON COLUMN learning_hub.badge_definitions.status IS 'active hoặc retired.';
COMMENT ON COLUMN learning_hub.badge_definitions.sort_no IS 'Thứ tự hiển thị.';
COMMENT ON COLUMN learning_hub.badge_definitions.created_by IS 'Mã cán bộ tạo; null với bộ huy hiệu khởi đầu do hệ thống gieo.';

CREATE TABLE learning_hub.user_badges (
    user_id varchar(20) NOT NULL,
    badge_id bigint NOT NULL,
    earned_at timestamptz NOT NULL DEFAULT now(),
    source varchar(20) NOT NULL,
    CONSTRAINT pk_user_badges PRIMARY KEY (user_id, badge_id),
    CONSTRAINT ck_user_badges_source CHECK (source IN ('EVENT', 'BACKFILL'))
);
CREATE INDEX idx_user_badges_badge ON learning_hub.user_badges (badge_id);
COMMENT ON TABLE learning_hub.user_badges IS 'Huy hiệu mỗi học viên đã nhận; không bao giờ bị xóa hay thu hồi. Mỗi (người, huy hiệu) một dòng nên trao lại không ghi thêm.';
COMMENT ON COLUMN learning_hub.user_badges.user_id IS 'Mã cán bộ học viên (ID logic không FK).';
COMMENT ON COLUMN learning_hub.user_badges.badge_id IS 'Huy hiệu (badge_definitions.badge_id, ID logic không FK).';
COMMENT ON COLUMN learning_hub.user_badges.earned_at IS 'Lúc nhận.';
COMMENT ON COLUMN learning_hub.user_badges.source IS 'EVENT: đạt khi sự kiện xảy ra (có thông báo). BACKFILL: trao âm thầm khi huy hiệu được tạo (không thông báo).';

COMMIT;
