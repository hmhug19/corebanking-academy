-- Soạn cùng trợ lý (ADR 0002): one drafting session per course the assistant drafts with its author, and one row per
-- step it reached (1 basic info, 2 outline, 3 rules and questions, 4 audience). A step holds the assistant's last
-- proposal as JSON and its state; the session holds the private source document, the summary of that document, and the
-- course once step 1 is confirmed. Kept apart from course_generation_jobs: that pipeline is retired and dropped later.
-- Relations are plain id columns, no physical foreign keys (guideline §13.2), not even from a step to its session:
-- the backend never deletes a session, and whoever deletes one deletes its steps with it. A DB that ran an earlier
-- copy of this script drops that copy's foreign key here.
-- "One open session per course" is checked by the service, not by a unique constraint.
-- Run as dev_user (the backend's role) on a DB that already has 2026-11-12-course-generation-jobs.sql. Safe to run again.
-- The backend uses these tables through JDBC at the first request: run it BEFORE deploying the backend.
--   psql -h <host> -U dev_user -d <database> -v ON_ERROR_STOP=1 -f docs/sql/upgrade/2026-11-24-course-drafting-sessions.sql
-- Rollback: docs/sql/upgrade/2026-11-24-course-drafting-sessions.rollback.sql
BEGIN;
SET LOCAL lock_timeout = '5s';

CREATE TABLE IF NOT EXISTS learning_hub.course_drafting_sessions (
    session_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id varchar(20) NOT NULL,
    owner_org_id bigint NOT NULL,
    source_document_id bigint,
    conversation_id bigint,
    course_id bigint,
    revision_id bigint,
    current_step smallint NOT NULL DEFAULT 1 CHECK (current_step BETWEEN 1 AND 4),
    status varchar(12) NOT NULL CHECK (status IN ('active', 'finished', 'manual', 'failed')),
    error_message varchar(500),
    hints jsonb NOT NULL DEFAULT '{}'::jsonb,
    source_summary jsonb,
    create_time timestamptz NOT NULL DEFAULT now(),
    update_time timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE learning_hub.course_drafting_sessions IS
    'Phiên Soạn cùng trợ lý: tài liệu nguồn riêng tư, khóa học nháp sau khi chốt bước 1, bước hiện tại và trạng thái.';
COMMENT ON COLUMN learning_hub.course_drafting_sessions.owner_user_id IS 'Người bắt đầu phiên; chỉ người này xem và thao tác.';
COMMENT ON COLUMN learning_hub.course_drafting_sessions.owner_org_id IS 'Đơn vị sở hữu khóa học sẽ tạo; do server quyết định, không do model.';
COMMENT ON COLUMN learning_hub.course_drafting_sessions.source_document_id IS 'Tài liệu nguồn (knowledge_documents, phạm vi course_source): chỉ người tải lên đọc được, không bao giờ được tìm kiếm.';
COMMENT ON COLUMN learning_hub.course_drafting_sessions.conversation_id IS 'Hội thoại trợ lý đã bắt đầu phiên, nơi trợ lý báo từng bước; NULL khi bắt đầu từ trang.';
COMMENT ON COLUMN learning_hub.course_drafting_sessions.course_id IS 'Khóa học nháp tạo khi chốt bước 1; NULL trước đó.';
COMMENT ON COLUMN learning_hub.course_drafting_sessions.revision_id IS 'Bản nháp của khóa học đó.';
COMMENT ON COLUMN learning_hub.course_drafting_sessions.current_step IS 'Bước đang làm: 1 thông tin cơ bản, 2 nội dung, 3 kiểm tra và điều kiện, 4 đối tượng và xuất bản.';
COMMENT ON COLUMN learning_hub.course_drafting_sessions.status IS 'active | finished | manual (người dùng tự điền) | failed.';
COMMENT ON COLUMN learning_hub.course_drafting_sessions.error_message IS 'Lỗi đọc cho người dùng khi phiên failed.';
COMMENT ON COLUMN learning_hub.course_drafting_sessions.hints IS 'Thông tin người dùng gửi kèm khi bắt đầu: tên, đối tượng, mức độ.';
COMMENT ON COLUMN learning_hub.course_drafting_sessions.source_summary IS 'Tóm tắt từng phần của tài liệu nguồn, dùng lại cho mọi bước và khi đề xuất lại.';

CREATE INDEX IF NOT EXISTS idx_course_drafting_sessions_owner
    ON learning_hub.course_drafting_sessions (owner_user_id, create_time DESC);
CREATE INDEX IF NOT EXISTS idx_course_drafting_sessions_course
    ON learning_hub.course_drafting_sessions (course_id) WHERE status = 'active';

CREATE TABLE IF NOT EXISTS learning_hub.course_drafting_steps (
    step_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id bigint NOT NULL,
    step_no smallint NOT NULL CHECK (step_no BETWEEN 1 AND 4),
    state varchar(10) NOT NULL CHECK (state IN ('proposing', 'proposed', 'confirmed', 'failed', 'manual')),
    proposal jsonb,
    notes jsonb NOT NULL DEFAULT '[]'::jsonb,
    error_message varchar(500),
    attempts integer NOT NULL DEFAULT 0,
    claimed_at timestamptz,
    stopped boolean NOT NULL DEFAULT false,
    update_time timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_course_drafting_steps_step UNIQUE (session_id, step_no)
);
COMMENT ON TABLE learning_hub.course_drafting_steps IS
    'Một bước của phiên Soạn cùng trợ lý: đề xuất mới nhất của trợ lý và trạng thái của bước.';
COMMENT ON COLUMN learning_hub.course_drafting_steps.state IS 'proposing | proposed | confirmed | failed | manual.';
COMMENT ON COLUMN learning_hub.course_drafting_steps.proposal IS 'Đề xuất của bước, đã kiểm theo schema; id chương trình/phân hệ không có trong danh sách được chọn đã bị bỏ.';
COMMENT ON COLUMN learning_hub.course_drafting_steps.notes IS 'Các dòng nhắc người dùng kiểm tra (tiếng Việt), hiện trong chat.';
COMMENT ON COLUMN learning_hub.course_drafting_steps.claimed_at IS 'Lúc worker nhận bước đang proposing; NULL nghĩa là đang chờ.';
COMMENT ON COLUMN learning_hub.course_drafting_steps.stopped IS 'Người dùng bấm Dừng khi bước đang soạn.';

ALTER TABLE learning_hub.course_drafting_steps DROP CONSTRAINT IF EXISTS course_drafting_steps_session_id_fkey;
COMMENT ON COLUMN learning_hub.course_drafting_steps.session_id IS 'Phiên Soạn cùng trợ lý (course_drafting_sessions); quan hệ logic, không có khóa ngoại.';

CREATE INDEX IF NOT EXISTS idx_course_drafting_steps_claim
    ON learning_hub.course_drafting_steps (state, step_id) WHERE claimed_at IS NULL;

COMMIT;
