-- Course content index: the text of every published course revision, cut into chunks with an embedding, so the
-- assistant can search lessons. One row per chunk in course_content_chunks; course_content_index records which
-- revisions are fully indexed. A revision is indexed in one transaction (chunks and the marker row together), so a
-- restart halfway leaves nothing behind and the next run starts that revision again.
-- Run once on a DB that already has the Learning and Knowledge baselines. Safe to run again.
-- The backend refuses to start without these tables (ddl-auto=validate): run it BEFORE deploying the backend.
--   psql -h <host> -U <user> -d <database> -v ON_ERROR_STOP=1 -f docs/sql/upgrade/2026-11-11-course-content-index.sql
-- Rollback: docs/sql/upgrade/2026-11-11-course-content-index.rollback.sql
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL search_path TO learning_hub, public;

CREATE TABLE IF NOT EXISTS learning_hub.course_content_chunks (
    chunk_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id bigint NOT NULL,
    revision_id bigint NOT NULL,
    chapter_id bigint NOT NULL,
    chapter_title varchar(255) NOT NULL,
    lesson_id bigint NOT NULL,
    lesson_title varchar(255) NOT NULL,
    block_id bigint NOT NULL,
    block_title varchar(255) NOT NULL,
    chunk_index integer NOT NULL,
    content text NOT NULL,
    token_estimate integer NOT NULL,
    embedding vector(1024) NOT NULL,
    create_time timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE learning_hub.course_content_chunks IS
    'Đoạn nội dung bài học của revision đã xuất bản kèm vector bge-m3 để trợ lý AI tìm kiếm. Quan hệ bằng cột ID thông thường, không FK.';
COMMENT ON COLUMN learning_hub.course_content_chunks.course_id IS 'Khóa học (courses.course_id).';
COMMENT ON COLUMN learning_hub.course_content_chunks.revision_id IS 'Revision đã xuất bản được lập chỉ mục (course_revisions.revision_id).';
COMMENT ON COLUMN learning_hub.course_content_chunks.chapter_id IS 'Chương chứa đoạn (course_chapters.chapter_id).';
COMMENT ON COLUMN learning_hub.course_content_chunks.chapter_title IS 'Tên chương lúc lập chỉ mục, dùng cho trích dẫn.';
COMMENT ON COLUMN learning_hub.course_content_chunks.lesson_id IS 'Bài học chứa đoạn (course_lessons.lesson_id).';
COMMENT ON COLUMN learning_hub.course_content_chunks.lesson_title IS 'Tên bài học lúc lập chỉ mục, dùng cho trích dẫn.';
COMMENT ON COLUMN learning_hub.course_content_chunks.block_id IS 'Khối nội dung chứa đoạn (lesson_blocks.block_id).';
COMMENT ON COLUMN learning_hub.course_content_chunks.block_title IS 'Tên khối lúc lập chỉ mục.';
COMMENT ON COLUMN learning_hub.course_content_chunks.chunk_index IS 'Thứ tự đoạn trong revision, bắt đầu từ 0.';
COMMENT ON COLUMN learning_hub.course_content_chunks.content IS 'Nội dung văn bản của đoạn (đã bỏ định dạng HTML).';
COMMENT ON COLUMN learning_hub.course_content_chunks.token_estimate IS 'Ước lượng số token từ số ký tự.';
COMMENT ON COLUMN learning_hub.course_content_chunks.embedding IS 'Vector bge-m3 1024 chiều của tên bài kèm nội dung đoạn.';

CREATE UNIQUE INDEX IF NOT EXISTS uq_course_content_chunks_revision
    ON learning_hub.course_content_chunks(revision_id, chunk_index);
CREATE INDEX IF NOT EXISTS idx_course_content_chunks_course
    ON learning_hub.course_content_chunks(course_id);
CREATE INDEX IF NOT EXISTS idx_course_content_chunks_lesson
    ON learning_hub.course_content_chunks(lesson_id);
CREATE INDEX IF NOT EXISTS idx_course_content_chunks_embedding
    ON learning_hub.course_content_chunks USING hnsw (embedding vector_cosine_ops);

CREATE TABLE IF NOT EXISTS learning_hub.course_content_index (
    revision_id bigint PRIMARY KEY,
    course_id bigint NOT NULL,
    chunk_count integer NOT NULL,
    indexed_time timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE learning_hub.course_content_index IS
    'Revision đã lập chỉ mục xong (ghi cùng transaction với các đoạn). Revision xuất bản mà chưa có hàng ở đây sẽ được worker lập chỉ mục.';
COMMENT ON COLUMN learning_hub.course_content_index.revision_id IS 'Revision đã lập chỉ mục (course_revisions.revision_id).';
COMMENT ON COLUMN learning_hub.course_content_index.course_id IS 'Khóa học của revision.';
COMMENT ON COLUMN learning_hub.course_content_index.chunk_count IS 'Số đoạn đã ghi; 0 khi revision không có văn bản.';
COMMENT ON COLUMN learning_hub.course_content_index.indexed_time IS 'Lúc lập chỉ mục xong.';

CREATE INDEX IF NOT EXISTS idx_course_content_index_course
    ON learning_hub.course_content_index(course_id);

COMMIT;
