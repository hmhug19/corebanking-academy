-- Soạn cùng trợ lý (ADR 0002): "Đề xuất lại" and "Thử lại" make the assistant work on a step again, so each one counts
-- against the same daily course generation allowance as starting a session or an old job. One row per request; the
-- allowance counts rows of the last 24 hours. Rows stay when their session goes, so deleting gives nothing back.
-- Relations are plain id columns, no foreign keys (guideline §6).
-- Run as dev_user (the backend's role) on a DB that already has 2026-11-24-course-drafting-sessions.sql. Safe to run
-- again. The backend reads this table on every start and "Đề xuất lại": run it BEFORE deploying the backend.
--   psql -h <host> -U dev_user -d <database> -v ON_ERROR_STOP=1 -f docs/sql/upgrade/2026-11-25-course-drafting-reproposals.sql
-- Rollback: docs/sql/upgrade/2026-11-25-course-drafting-reproposals.rollback.sql
BEGIN;
SET LOCAL lock_timeout = '5s';

CREATE TABLE IF NOT EXISTS learning_hub.course_drafting_reproposals (
    reproposal_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id bigint NOT NULL,
    step_no smallint NOT NULL CHECK (step_no BETWEEN 1 AND 4),
    owner_user_id varchar(20) NOT NULL,
    create_time timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE learning_hub.course_drafting_reproposals IS
    'Mỗi lần người dùng bấm Đề xuất lại hoặc Thử lại một bước của Soạn cùng trợ lý; tính vào giới hạn tạo khóa học bằng AI mỗi ngày.';
COMMENT ON COLUMN learning_hub.course_drafting_reproposals.session_id IS 'Phiên Soạn cùng trợ lý (course_drafting_sessions).';
COMMENT ON COLUMN learning_hub.course_drafting_reproposals.step_no IS 'Bước được đề xuất lại: 1 đến 4.';
COMMENT ON COLUMN learning_hub.course_drafting_reproposals.owner_user_id IS 'Người yêu cầu, chủ phiên.';

CREATE INDEX IF NOT EXISTS idx_course_drafting_reproposals_owner
    ON learning_hub.course_drafting_reproposals (owner_user_id, create_time DESC);

COMMIT;
