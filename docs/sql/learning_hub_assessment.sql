-- PostgreSQL 14+. Quiz Engine (P0): ngân hàng câu hỏi, cấu hình bài thi, lượt thi và chấm điểm.
-- Chạy một lần sau Identity và Learning trên môi trường đã review.
-- Không FK, không REFERENCES, không DROP, không seed. Không tự chạy lúc startup; giữ ddl-auto=validate, Flyway tắt.
-- Mã trạng thái dùng IN HOA theo thiết kế assessment_schema.sql; người dùng tham chiếu users.user_id (varchar 20).
BEGIN;

CREATE TABLE learning_hub.competencies (
    competency_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(50) NOT NULL,
    name varchar(255) NOT NULL,
    description text,
    parent_id bigint,
    sort_no integer NOT NULL DEFAULT 0,
    status varchar(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE')),
    is_deleted boolean NOT NULL DEFAULT false,
    created_by varchar(20) NOT NULL,
    updated_by varchar(20) NOT NULL,
    row_version bigint NOT NULL DEFAULT 0,
    create_time timestamptz NOT NULL DEFAULT now(),
    update_time timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE learning_hub.competencies IS 'Nhóm kiến thức/năng lực (master data) dùng cho báo cáo năng lực.';
COMMENT ON COLUMN learning_hub.competencies.code IS 'Mã nhóm, duy nhất trong các bản ghi chưa xóa mềm.';
COMMENT ON COLUMN learning_hub.competencies.parent_id IS 'ID nhóm cha (logic, không FK); NULL là nhóm gốc.';
COMMENT ON COLUMN learning_hub.competencies.status IS 'ACTIVE = đang dùng; INACTIVE = không gắn vào câu mới, báo cáo cũ vẫn giữ.';
COMMENT ON COLUMN learning_hub.competencies.row_version IS 'Optimistic locking chống ghi đè thay đổi.';

CREATE TABLE learning_hub.questions (
    question_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(50),
    program_id bigint,
    course_id bigint,
    lesson_id bigint,
    competency_id bigint NOT NULL,
    question_type varchar(20) NOT NULL CHECK (question_type IN ('SINGLE', 'MULTIPLE')),
    content text NOT NULL,
    explanation text,
    difficulty varchar(10) NOT NULL DEFAULT 'MEDIUM' CHECK (difficulty IN ('EASY', 'MEDIUM', 'HARD')),
    points numeric(6,2) NOT NULL DEFAULT 1 CHECK (points > 0),
    status varchar(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE')),
    content_version integer NOT NULL DEFAULT 1 CHECK (content_version > 0),
    is_deleted boolean NOT NULL DEFAULT false,
    created_by varchar(20) NOT NULL,
    updated_by varchar(20) NOT NULL,
    row_version bigint NOT NULL DEFAULT 0,
    create_time timestamptz NOT NULL DEFAULT now(),
    update_time timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE learning_hub.questions IS 'Ngân hàng câu hỏi theo chương trình; câu đã phát đề chỉ xóa mềm hoặc INACTIVE.';
COMMENT ON COLUMN learning_hub.questions.code IS 'Mã câu hỏi; để trống thì backend sinh Q<ID>.';
COMMENT ON COLUMN learning_hub.questions.program_id IS 'Chương trình sở hữu ngân hàng (logic, không FK); câu hỏi mới dùng chung trong chương trình.';
COMMENT ON COLUMN learning_hub.questions.course_id IS 'Nguồn khóa học của client cũ; NULL với câu hỏi tạo theo chương trình.';
COMMENT ON COLUMN learning_hub.questions.lesson_id IS 'ID bài học thuộc khóa (logic, tùy chọn) để gợi ý ôn lại.';
COMMENT ON COLUMN learning_hub.questions.competency_id IS 'ID nhóm năng lực (logic, không FK).';
COMMENT ON COLUMN learning_hub.questions.content_version IS 'Tăng khi sửa nội dung/phương án/đáp án của câu đã từng được phát đề.';
COMMENT ON COLUMN learning_hub.questions.row_version IS 'Optimistic locking chống ghi đè thay đổi.';

CREATE TABLE learning_hub.question_options (
    option_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id bigint NOT NULL,
    content text NOT NULL,
    is_correct boolean NOT NULL DEFAULT false,
    sort_no integer NOT NULL DEFAULT 0,
    is_deleted boolean NOT NULL DEFAULT false,
    create_time timestamptz NOT NULL DEFAULT now(),
    update_time timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE learning_hub.question_options IS 'Phương án trả lời; sửa tại chỗ giữ nguyên ID vì ID được chụp vào đề đã phát.';
COMMENT ON COLUMN learning_hub.question_options.is_correct IS 'Đáp án đúng; không bao giờ trả cho học viên khi đang thi.';

CREATE TABLE learning_hub.quizzes (
    quiz_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id bigint NOT NULL,
    title varchar(255) NOT NULL,
    description text,
    quiz_type varchar(20) NOT NULL DEFAULT 'FINAL_EXAM' CHECK (quiz_type IN ('PRACTICE', 'FINAL_EXAM')),
    status varchar(20) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'PUBLISHED', 'CLOSED')),
    selection_mode varchar(20) NOT NULL DEFAULT 'RANDOM_POOL' CHECK (selection_mode IN ('FIXED', 'RANDOM_POOL')),
    question_count integer NOT NULL CHECK (question_count BETWEEN 1 AND 200),
    shuffle_questions boolean NOT NULL DEFAULT true,
    shuffle_options boolean NOT NULL DEFAULT true,
    time_limit_minutes integer NOT NULL CHECK (time_limit_minutes BETWEEN 1 AND 240),
    open_at timestamptz,
    close_at timestamptz,
    grace_seconds integer NOT NULL DEFAULT 5 CHECK (grace_seconds BETWEEN 0 AND 300),
    pass_percent numeric(5,2) NOT NULL CHECK (pass_percent > 0 AND pass_percent <= 100),
    scoring_mode varchar(20) NOT NULL DEFAULT 'ALL_OR_NOTHING' CHECK (scoring_mode IN ('ALL_OR_NOTHING', 'PARTIAL')),
    score_method varchar(20) NOT NULL DEFAULT 'BEST' CHECK (score_method IN ('BEST', 'LAST')),
    review_policy varchar(20) NOT NULL DEFAULT 'AFTER_SUBMIT'
        CHECK (review_policy IN ('NEVER', 'AFTER_SUBMIT', 'AFTER_PASS', 'AFTER_CLOSE')),
    max_attempts integer NOT NULL DEFAULT 3 CHECK (max_attempts BETWEEN 1 AND 20),
    retake_wait_hours integer NOT NULL DEFAULT 0 CHECK (retake_wait_hours BETWEEN 0 AND 720),
    allow_retake_after_pass boolean NOT NULL DEFAULT false,
    require_lessons_completed boolean NOT NULL DEFAULT false,
    published_at timestamptz,
    is_deleted boolean NOT NULL DEFAULT false,
    created_by varchar(20) NOT NULL,
    updated_by varchar(20) NOT NULL,
    row_version bigint NOT NULL DEFAULT 0,
    create_time timestamptz NOT NULL DEFAULT now(),
    update_time timestamptz NOT NULL DEFAULT now(),
    CHECK (open_at IS NULL OR close_at IS NULL OR close_at > open_at)
);
COMMENT ON TABLE learning_hub.quizzes IS 'Cấu hình bài thi của khóa học; lượt thi chụp lại thông số chấm khi bắt đầu.';
COMMENT ON COLUMN learning_hub.quizzes.course_id IS 'ID khóa học (logic, không FK).';
COMMENT ON COLUMN learning_hub.quizzes.quiz_type IS 'PRACTICE = luyện tập; FINAL_EXAM = thi cuối khóa (tối đa 1 đề/khóa).';
COMMENT ON COLUMN learning_hub.quizzes.close_at IS 'Đóng đề; deadline của lượt đang làm bị chặn tại đây.';
COMMENT ON COLUMN learning_hub.quizzes.grace_seconds IS 'Ân hạn sau deadline vẫn nhận lưu/nộp (bù trễ mạng).';
COMMENT ON COLUMN learning_hub.quizzes.score_method IS 'Điểm cuối và trạng thái đạt: BEST = lượt cao nhất, LAST = lượt chấm gần nhất.';
COMMENT ON COLUMN learning_hub.quizzes.row_version IS 'Optimistic locking chống ghi đè cấu hình và pool câu hỏi.';

CREATE TABLE learning_hub.quiz_questions (
    quiz_question_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id bigint NOT NULL,
    question_id bigint NOT NULL,
    sort_no integer NOT NULL DEFAULT 0,
    points numeric(6,2) CHECK (points IS NULL OR points > 0),
    created_by varchar(20) NOT NULL,
    create_time timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE learning_hub.quiz_questions IS 'Pool câu hỏi của đề; xóa dòng được phép vì lịch sử nằm ở attempt_questions.';
COMMENT ON COLUMN learning_hub.quiz_questions.points IS 'Điểm của câu trong đề; NULL = dùng questions.points.';

CREATE TABLE learning_hub.quiz_attempts (
    attempt_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id bigint NOT NULL,
    user_id varchar(20) NOT NULL,
    enrollment_id bigint NOT NULL,
    attempt_no integer NOT NULL CHECK (attempt_no > 0),
    status varchar(20) NOT NULL DEFAULT 'IN_PROGRESS'
        CHECK (status IN ('IN_PROGRESS', 'SUBMITTED', 'AUTO_SUBMITTED', 'VOIDED')),
    submit_type varchar(20) CHECK (submit_type IN ('MANUAL', 'TIMEOUT', 'QUIZ_CLOSED', 'ADMIN')),
    started_at timestamptz NOT NULL,
    deadline_at timestamptz NOT NULL,
    submitted_at timestamptz,
    last_saved_at timestamptz,
    time_limit_minutes integer NOT NULL,
    pass_percent numeric(5,2) NOT NULL,
    scoring_mode varchar(20) NOT NULL,
    grace_seconds integer NOT NULL,
    total_questions integer NOT NULL,
    max_score numeric(8,2) NOT NULL,
    correct_count integer,
    raw_score numeric(8,2),
    score_percent numeric(5,2),
    passed boolean,
    graded_at timestamptz,
    org_id bigint,
    team_id bigint,
    client_ip varchar(45),
    user_agent varchar(500),
    void_reason text,
    voided_by varchar(20),
    voided_at timestamptz,
    create_time timestamptz NOT NULL DEFAULT now(),
    update_time timestamptz NOT NULL DEFAULT now(),
    CHECK (deadline_at > started_at),
    CHECK (status IN ('IN_PROGRESS', 'VOIDED') OR submitted_at IS NOT NULL)
);
COMMENT ON TABLE learning_hub.quiz_attempts IS 'Lượt thi; lịch sử không xóa, lượt sai/gian lận chuyển VOIDED.';
COMMENT ON COLUMN learning_hub.quiz_attempts.user_id IS 'Mã cán bộ người thi (logic, không FK).';
COMMENT ON COLUMN learning_hub.quiz_attempts.enrollment_id IS 'Lần học (course_enrollments) dùng để kiểm quyền thi; không dùng đếm lượt.';
COMMENT ON COLUMN learning_hub.quiz_attempts.deadline_at IS 'min(started_at + time_limit, quizzes.close_at), theo giờ server.';
COMMENT ON COLUMN learning_hub.quiz_attempts.pass_percent IS 'Snapshot cấu hình lúc bắt đầu; passed xét theo giá trị này.';
COMMENT ON COLUMN learning_hub.quiz_attempts.score_percent IS 'raw_score/max_score*100 cắt xuống 2 chữ số; passed so sánh trên giá trị chưa làm tròn.';
COMMENT ON COLUMN learning_hub.quiz_attempts.org_id IS 'Đơn vị tại thời điểm thi.';

CREATE TABLE learning_hub.attempt_questions (
    attempt_question_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id bigint NOT NULL,
    question_id bigint NOT NULL,
    question_version integer NOT NULL,
    display_order integer NOT NULL CHECK (display_order > 0),
    question_type varchar(20) NOT NULL CHECK (question_type IN ('SINGLE', 'MULTIPLE')),
    content_snapshot text NOT NULL,
    options_snapshot jsonb NOT NULL CHECK (jsonb_typeof(options_snapshot) = 'array'),
    correct_option_ids jsonb NOT NULL
        CHECK (jsonb_typeof(correct_option_ids) = 'array' AND jsonb_array_length(correct_option_ids) > 0),
    explanation_snapshot text,
    points numeric(6,2) NOT NULL CHECK (points > 0),
    competency_id bigint,
    difficulty varchar(10),
    is_flagged boolean NOT NULL DEFAULT false,
    create_time timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE learning_hub.attempt_questions IS 'Snapshot đề đã phát; chấm và xem lại chỉ đọc bảng này, không đọc câu hỏi gốc.';
COMMENT ON COLUMN learning_hub.attempt_questions.options_snapshot IS 'Phương án theo thứ tự hiển thị: [{"id":11,"content":"..."}]; không có is_correct.';
COMMENT ON COLUMN learning_hub.attempt_questions.correct_option_ids IS 'ID đáp án đúng; bí mật khi lượt đang IN_PROGRESS.';

CREATE TABLE learning_hub.attempt_answers (
    answer_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_question_id bigint NOT NULL,
    selected_option_ids jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(selected_option_ids) = 'array'),
    is_correct boolean,
    score_awarded numeric(6,2) CHECK (score_awarded IS NULL OR score_awarded >= 0),
    answered_at timestamptz NOT NULL,
    changed_at timestamptz,
    change_count integer NOT NULL DEFAULT 0
);
COMMENT ON TABLE learning_hub.attempt_answers IS 'Đáp án học viên chọn, 1 dòng/câu; lưu ngay khi chọn để đổi máy không mất bài.';
COMMENT ON COLUMN learning_hub.attempt_answers.selected_option_ids IS 'ID phương án đã chọn; [] = bỏ trống.';

CREATE TABLE learning_hub.quiz_attempt_grants (
    grant_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id bigint NOT NULL,
    user_id varchar(20) NOT NULL,
    extra_attempts integer NOT NULL CHECK (extra_attempts > 0),
    reason text NOT NULL,
    granted_by varchar(20) NOT NULL,
    granted_at timestamptz NOT NULL DEFAULT now(),
    is_deleted boolean NOT NULL DEFAULT false,
    deleted_by varchar(20),
    deleted_at timestamptz
);
COMMENT ON TABLE learning_hub.quiz_attempt_grants IS 'Cấp thêm lượt thi riêng cho một học viên; thu hồi bằng is_deleted.';

CREATE TABLE learning_hub.attempt_regrades (
    regrade_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id varchar(36) NOT NULL,
    quiz_id bigint NOT NULL,
    attempt_id bigint NOT NULL,
    question_id bigint NOT NULL,
    reason text NOT NULL,
    old_correct_option_ids jsonb NOT NULL,
    new_correct_option_ids jsonb NOT NULL,
    old_correct_count integer,
    new_correct_count integer,
    old_raw_score numeric(8,2),
    new_raw_score numeric(8,2),
    old_score_percent numeric(5,2),
    new_score_percent numeric(5,2),
    old_passed boolean,
    new_passed boolean,
    regraded_by varchar(20) NOT NULL,
    regraded_at timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE learning_hub.attempt_regrades IS 'Lịch sử chấm lại: mỗi dòng là một lượt đã áp dụng đáp án mới; chỉ ghi thay đổi có lợi cho học viên.';
COMMENT ON COLUMN learning_hub.attempt_regrades.batch_id IS 'Mã đợt chấm lại (UUID) gom các lượt cùng một lần thao tác.';
COMMENT ON COLUMN learning_hub.attempt_regrades.old_correct_option_ids IS 'Đáp án đúng trong snapshot trước khi chấm lại.';

CREATE UNIQUE INDEX ux_asm_competencies_code ON learning_hub.competencies (code) WHERE NOT is_deleted;
CREATE INDEX ix_asm_competencies_parent ON learning_hub.competencies (parent_id);
CREATE UNIQUE INDEX ux_asm_questions_code ON learning_hub.questions (code) WHERE code IS NOT NULL AND NOT is_deleted;
CREATE INDEX ix_asm_questions_program ON learning_hub.questions (program_id, status) WHERE NOT is_deleted;
CREATE INDEX ix_asm_questions_course ON learning_hub.questions (course_id, status) WHERE NOT is_deleted;
CREATE INDEX ix_asm_questions_competency ON learning_hub.questions (competency_id, difficulty) WHERE NOT is_deleted;
CREATE INDEX ix_asm_question_options_question ON learning_hub.question_options (question_id, sort_no) WHERE NOT is_deleted;
CREATE INDEX ix_asm_quizzes_course ON learning_hub.quizzes (course_id) WHERE NOT is_deleted;
CREATE UNIQUE INDEX ux_asm_quizzes_final ON learning_hub.quizzes (course_id) WHERE quiz_type = 'FINAL_EXAM' AND NOT is_deleted;
CREATE UNIQUE INDEX ux_asm_quiz_questions ON learning_hub.quiz_questions (quiz_id, question_id);
CREATE INDEX ix_asm_quiz_questions_question ON learning_hub.quiz_questions (question_id);
CREATE UNIQUE INDEX ux_asm_quiz_attempts_no ON learning_hub.quiz_attempts (quiz_id, user_id, attempt_no);
CREATE UNIQUE INDEX ux_asm_quiz_attempts_running ON learning_hub.quiz_attempts (quiz_id, user_id) WHERE status = 'IN_PROGRESS';
CREATE INDEX ix_asm_quiz_attempts_expire ON learning_hub.quiz_attempts (deadline_at) WHERE status = 'IN_PROGRESS';
CREATE INDEX ix_asm_quiz_attempts_report ON learning_hub.quiz_attempts (quiz_id, status, submitted_at);
CREATE INDEX ix_asm_quiz_attempts_org ON learning_hub.quiz_attempts (org_id, submitted_at);
CREATE UNIQUE INDEX ux_asm_attempt_questions_order ON learning_hub.attempt_questions (attempt_id, display_order);
CREATE UNIQUE INDEX ux_asm_attempt_questions_question ON learning_hub.attempt_questions (attempt_id, question_id);
CREATE INDEX ix_asm_attempt_questions_item ON learning_hub.attempt_questions (question_id, question_version);
CREATE UNIQUE INDEX ux_asm_attempt_answers ON learning_hub.attempt_answers (attempt_question_id);
CREATE INDEX ix_asm_quiz_attempt_grants ON learning_hub.quiz_attempt_grants (quiz_id, user_id) WHERE NOT is_deleted;
CREATE INDEX ix_asm_attempt_regrades_attempt ON learning_hub.attempt_regrades (attempt_id, regraded_at);
CREATE INDEX ix_asm_attempt_regrades_quiz ON learning_hub.attempt_regrades (quiz_id, batch_id);

COMMIT;
