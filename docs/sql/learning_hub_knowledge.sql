-- PostgreSQL 14+ với extension pgvector (image pgvector/pgvector:pg16). Bổ sung kho tri thức "Trợ lý AI" sau Identity
-- và Learning, chỉ chạy một lần trên môi trường đã review. Không FK, không REFERENCES, không DROP, không seed.
-- Không tự chạy lúc startup; giữ ddl-auto=validate và Flyway tắt.
BEGIN;

-- Extension đặt trong schema learning_hub: ứng dụng chạy với currentSchema=learning_hub nên kiểu vector và toán tử
-- <=> phải nằm trong schema này mới dùng được mà không cần qualify. Nếu extension đã có sẵn ở schema khác (ví dụ
-- public), thêm schema đó vào currentSchema của DB_URL (currentSchema=learning_hub,public).
SET LOCAL search_path TO learning_hub, public;
CREATE EXTENSION IF NOT EXISTS vector WITH SCHEMA learning_hub;

-- 01. Tài liệu: đồng thời là hàng đợi xử lý nền (worker nhận bản ghi status = 'queued' bằng FOR UPDATE SKIP LOCKED).
CREATE TABLE learning_hub.knowledge_documents (
    document_id   bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uploaded_by   varchar(20)  NOT NULL,
    file_name     varchar(255) NOT NULL,
    mime_type     varchar(100) NOT NULL,
    size_bytes    bigint       NOT NULL,
    storage_key   varchar(100) NOT NULL,
    status        varchar(20)  NOT NULL CHECK (status IN ('queued', 'processing', 'ready', 'failed')),
    error_message varchar(500),
    page_count    integer,
    chunk_count   integer      NOT NULL DEFAULT 0,
    attempts      integer      NOT NULL DEFAULT 0,
    create_time   timestamptz  NOT NULL DEFAULT now(),
    started_at    timestamptz,
    processed_at  timestamptz
);
COMMENT ON TABLE learning_hub.knowledge_documents IS
    'Tài liệu trong kho tri thức dùng chung của Trợ lý AI; đồng thời là hàng đợi xử lý nền theo status.';
COMMENT ON COLUMN learning_hub.knowledge_documents.document_id IS 'ID tài liệu tự tăng.';
COMMENT ON COLUMN learning_hub.knowledge_documents.uploaded_by IS
    'Mã cán bộ tải lên; tham chiếu logic users.user_id, không có FK.';
COMMENT ON COLUMN learning_hub.knowledge_documents.file_name IS 'Tên tệp gốc, chỉ để hiển thị.';
COMMENT ON COLUMN learning_hub.knowledge_documents.mime_type IS 'Loại tệp backend nhận diện, không tin khai báo của trình duyệt.';
COMMENT ON COLUMN learning_hub.knowledge_documents.size_bytes IS 'Dung lượng tệp tính bằng byte.';
COMMENT ON COLUMN learning_hub.knowledge_documents.storage_key IS
    'Tên tệp UUID trong thư mục app.knowledge.storage-dir; không trả cho frontend.';
COMMENT ON COLUMN learning_hub.knowledge_documents.status IS
    'queued (chờ), processing (đang xử lý), ready (sẵn sàng tìm kiếm), failed (không xử lý được).';
COMMENT ON COLUMN learning_hub.knowledge_documents.error_message IS 'Thông báo tiếng Việt hiển thị cho người dùng khi status = failed.';
COMMENT ON COLUMN learning_hub.knowledge_documents.page_count IS 'Số trang; chỉ có với PDF.';
COMMENT ON COLUMN learning_hub.knowledge_documents.chunk_count IS 'Số đoạn đã lưu trong knowledge_document_chunks.';
COMMENT ON COLUMN learning_hub.knowledge_documents.attempts IS 'Số lần worker đã nhận xử lý tài liệu.';
COMMENT ON COLUMN learning_hub.knowledge_documents.create_time IS 'DB sinh thời điểm tải lên.';
COMMENT ON COLUMN learning_hub.knowledge_documents.started_at IS 'Thời điểm worker nhận xử lý lần gần nhất.';
COMMENT ON COLUMN learning_hub.knowledge_documents.processed_at IS 'Thời điểm xử lý xong (ready hoặc failed).';

CREATE INDEX idx_knowledge_documents_queue ON learning_hub.knowledge_documents(status, create_time);
CREATE INDEX idx_knowledge_documents_uploader ON learning_hub.knowledge_documents(uploaded_by, create_time DESC);
CREATE INDEX idx_knowledge_documents_created ON learning_hub.knowledge_documents(create_time DESC);

-- 02. Đoạn văn bản và vector nhúng. Đoạn của một tài liệu được ghi cùng transaction đặt status = 'ready'.
CREATE TABLE learning_hub.knowledge_document_chunks (
    chunk_id       bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id    bigint       NOT NULL,
    chunk_index    integer      NOT NULL,
    content        text         NOT NULL,
    page_number    integer,
    line_start     integer      NOT NULL,
    line_end       integer      NOT NULL,
    token_estimate integer      NOT NULL,
    embedding      vector(1024) NOT NULL
);
COMMENT ON TABLE learning_hub.knowledge_document_chunks IS
    'Đoạn văn bản của tài liệu đã xử lý kèm vector nhúng bge-m3 để tìm kiếm ngữ nghĩa.';
COMMENT ON COLUMN learning_hub.knowledge_document_chunks.chunk_id IS 'ID đoạn tự tăng.';
COMMENT ON COLUMN learning_hub.knowledge_document_chunks.document_id IS
    'Tài liệu chứa đoạn; tham chiếu logic knowledge_documents.document_id, không có FK.';
COMMENT ON COLUMN learning_hub.knowledge_document_chunks.chunk_index IS 'Thứ tự đoạn trong tài liệu, bắt đầu từ 0.';
COMMENT ON COLUMN learning_hub.knowledge_document_chunks.content IS 'Nội dung đoạn, dùng làm ngữ cảnh cho mô hình và trích dẫn.';
COMMENT ON COLUMN learning_hub.knowledge_document_chunks.page_number IS 'Số trang bắt đầu từ 1; null với .md và .docx.';
COMMENT ON COLUMN learning_hub.knowledge_document_chunks.line_start IS 'Dòng đầu của đoạn (trong trang với PDF).';
COMMENT ON COLUMN learning_hub.knowledge_document_chunks.line_end IS 'Dòng cuối của đoạn (trong trang với PDF).';
COMMENT ON COLUMN learning_hub.knowledge_document_chunks.token_estimate IS 'Ước lượng số token từ số ký tự.';
COMMENT ON COLUMN learning_hub.knowledge_document_chunks.embedding IS 'Vector bge-m3 1024 chiều, đã chuẩn hóa L2 bởi Ollama.';

CREATE UNIQUE INDEX uq_knowledge_chunks_document
    ON learning_hub.knowledge_document_chunks(document_id, chunk_index);
CREATE INDEX idx_knowledge_chunks_embedding ON learning_hub.knowledge_document_chunks
    USING hnsw (embedding vector_cosine_ops);

COMMIT;
